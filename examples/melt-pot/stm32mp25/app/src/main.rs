//! melt-pot CA35 application: receives temperature readings from the CM33 over
//! the generated `sensor` transceiver, runs an OP-TEE threshold check, and
//! serves the verdict to a Cog/WebKit HMI.
//!
//! The UIO bring-up, IPC transceivers, and defmt console live in
//! `consortium.gen.rs`, generated by the `consortium` build pipeline from
//! `../Consortium.toml` and `include!`d below. Its `async init()` opens the UIO
//! devices, runs every descriptor handshake, spawns the defmt console, and
//! returns `ConsortiumEndpoints`, whose `ipc_shm.sensor` field is a ready
//! `Transceiver<Command, SensorReading>` (this core sends `Command`, receives
//! `SensorReading`).

