/// Status shared between the IPC receive task and the HMI bridge.
#[derive(serde::Serialize, serde::Deserialize, Clone)]
struct Status {
    temperature_mdc: i32,
    seq: u32,
    within_limits: bool,
}

#[tokio::main]
async fn main() {
    tracing_subscriber::fmt::init();
    let state: Arc<Mutex<Option<Status>>> = Arc::new(Mutex::new(None));
    tracing::info!("melt-pot: starting CA35 application; waiting for IPC bring-up");
    let handle = tokio::runtime::Handle::current();
    tracing::info!("melt-pot: runtime handle: {handle:?}");

    // Bring up UIO + IPC + defmt console via the generated init(). On a plain
    // Linux development host (no `/dev/uioN`) this fails; the HMI still runs,
    // just without live sensor data.
    match init().await {
        Ok(endpoints) => {
            tracing::info!("melt-pot: IPC bring-up complete; starting receive loop");
            let state_ipc = Arc::clone(&state);
            tokio::spawn(async move {
                consortium_runtime_app::log::trace!("melt-pot: IPC receive loop started");
                // `endpoints` owns the UIO devices and the defmt console, so keep
                // it alive for the whole receive loop.
                let mut endpoints = endpoints;
                loop {
                    consortium_runtime_app::log::trace!("melt-pot: waiting for IPC message");
                    match endpoints.ipc_shm.sensor.recv().await {
                        Ok(msg) => {
                            let reading: SensorReading = msg.into_inner();
                            let within_limits = tee_check(reading.temperature_mdc);
                            *state_ipc.lock().unwrap() = Some(Status {
                                temperature_mdc: reading.temperature_mdc,
                                seq: reading.seq,
                                within_limits,
                            });
                        }
                        Err(e) => {
                            eprintln!("melt-pot: ipc recv error: {e}");
                            break;
                        }
                    }
                }
            });
        }
        Err(e) => {
            eprintln!("melt-pot: IPC bring-up unavailable ({e:?}); HMI runs without live data");
        }
    }

    // // ── HMI bridge ───────────────────────────────────────────────────────────
    // let mut bridge = Bridge::with_runtime(handle);

    // let state_hmi = Arc::clone(&state);
    // bridge.handle("get_status", move |_payload| {
    //     match state_hmi.lock().unwrap().clone() {
    //         Some(s) => serde_json::to_string(&s).unwrap_or_else(|_| "null".into()),
    //         None => "null".into(),
    //     }
    // });

    // let app = KioskApp::new("melt-pot-stm32mp25", None, None).expect("KioskApp init");
    // app.attach_bridge(bridge).expect("bridge attach");
    // app.load().expect("HMI load");

    // Run the GLib main loop on this thread (required by WebKit/Cog). The tokio
    // worker threads continue running the IPC receive loop concurrently.
    // glib::MainLoop::new(None, false).run();

    tokio::time::sleep(std::time::Duration::from_millis(5)).await;
}

