/// Interrupt vectors for this endpoint's generated bring-up.
#[cfg(target_arch = "arm")]
mod __consortium_vectors {
    use ::consortium_hal_stm32mp2::interrupt;
    #[::consortium_hal_stm32mp2::interrupt]
    fn TIM2() {
        ::consortium_hal_stm32mp2::timer_driver::on_timer_interrupt();
    }
    const _: () = ::core::assert!(
        ::consortium_hal_stm32mp2::Interrupt::IPCC1_RX as u16 == 171u16,
        "IPCC1_RX is interrupt 171 in this core's Consortium chip map but not in the chip PAC's interrupt table; the generated vector and the NVIC enable would refer to different lines"
    );
    #[::consortium_hal_stm32mp2::interrupt]
    fn IPCC1_RX() {
        ::consortium_ipc_doorbell_ipcc::notify_rx_occupied_interrupt::<
            ::consortium_ipc::Secondary,
            1usize,
        >();
    }
}
/// Runtime bring-up policy. Enabled manifest steps default on.
#[cfg(target_arch = "arm")]
#[non_exhaustive]
pub struct Config {
    pub logger: bool,
    pub mpu: bool,
    pub nvic: bool,
    pub time_driver: bool,
}
#[cfg(target_arch = "arm")]
impl ::core::default::Default for Config {
    fn default() -> Self {
        Self {
            logger: true,
            mpu: true,
            nvic: true,
            time_driver: true,
        }
    }
}
/// Brings up synchronous platform resources and installs each
/// unconnected IPC transport into its generated endpoint state.
#[cfg(target_arch = "arm")]
fn init(config: Config) -> (Peripherals, Channels) {
    if config.logger {
        ::consortium_dbg::logger::ConsortiumLogger::init();
    }
    ::consortium_runtime_mcu::log::trace!(
        "consortium controller init: mpu/nvic bring-up"
    );
    // SAFETY: `init` runs once during controller bring-up, in
    // privileged mode, before any other code touches the MPU or
    // cache-control peripherals.
    let mut __core = unsafe { ::cortex_m::Peripherals::steal() };
    if config.mpu {
        // SAFETY: `init` holds exclusive privileged MPU access during
        // bring-up; `base`/`size` are this core's validated shared
        // region from the Consortium hardware layout.
        unsafe {
            ::consortium_runtime_mcu::mpu::disable_cache(
                &mut __core.MPU,
                0u8,
                537280512u32,
                16384u32,
            );
            ::consortium_runtime_mcu::log::trace!(
                "consortium controller init: MPU carveout {} base={:#010x} size={:#010x}",
                0u8, 537280512u32, 16384u32
            );
        }
    }
    if config.nvic {
        ::consortium_hal_stm32mp2::hal::nvic::unpend(
            ::consortium_hal_stm32mp2::Interrupt::IPCC1_RX,
        );
        // SAFETY: the interrupt comes from the validated Consortium
        // hardware database for this visible core, and the application
        // owns the matching vector.
        unsafe {
            ::consortium_hal_stm32mp2::hal::nvic::set_priority(
                ::consortium_hal_stm32mp2::Interrupt::IPCC1_RX,
                0x80u8,
            );
            ::consortium_hal_stm32mp2::hal::nvic::enable(
                ::consortium_hal_stm32mp2::Interrupt::IPCC1_RX,
            );
        }
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: NVIC enabled {} at priority 0x80 (id={})",
            "IPCC1_RX", 171u32
        );
    }
    let __p = ::consortium_hal_stm32mp2::init();
    if config.time_driver {
        ::consortium_hal_stm32mp2::timer_driver::bringup(__p.TIM2);
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: time driver up"
        );
    }
    __consortium_install_channels(__p.IPCC1);
    let channels = Channels::take();
    let peripherals = Peripherals { SPI1: __p.SPI1 };
    ::consortium_runtime_mcu::log::trace!("consortium controller init: resources ready");
    (peripherals, channels)
}
/// Error union suitable for `#[consortium_runtime_mcu::main]`.
#[cfg(target_arch = "arm")]
#[cfg_attr(target_os = "none", derive(Debug, defmt::Format))]
#[cfg_attr(not(target_os = "none"), derive(Debug))]
#[allow(dead_code)]
enum ConsortiumError {
    Connect(::consortium_ipc_transport_memory::ConnectError),
}
#[cfg(target_arch = "arm")]
impl ::core::convert::From<::consortium_ipc_transport_memory::ConnectError>
for ConsortiumError {
    fn from(e: ::consortium_ipc_transport_memory::ConnectError) -> Self {
        Self::Connect(e)
    }
}
