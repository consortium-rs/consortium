//! melt-pot CM33 firmware: streams simulated temperature readings to the CA35
//! over the generated `sensor` IPC transceiver.
//!
//! All of the shared-memory / doorbell / MPU / NVIC wiring lives in
//! `consortium.gen.rs`, which the `consortium` build pipeline generates from
//! `../Consortium.toml` and this file `include!`s. That module exposes:
//!
//! - `init()` — brings up the MPU + doorbell interrupt and constructs the
//!   (disconnected) `IpcMemoryEndpoints`;
//! - `IpcMemoryEndpoints::connect().await` — runs the descriptor handshake and
//!   returns `IpcMemoryEndpointsConnected`, whose `sensor` field is a ready
//!   `Transceiver<SensorReading, Command>` (this core sends `SensorReading`,
//!   receives `Command`).

#![no_std]
#![no_main]

use core::{ptr::write_volatile, sync::atomic::compiler_fence};

use embassy_executor::Spawner;
use embassy_time::Timer;
use melt_pot_shared::SensorReading;
use consortium_hal_stm32mp2::interrupt;

// Generated by `consortium build`; see the module docs above. Depending on
// `consortium-dbg` with the `logger` feature also registers its defmt sink, so
// the `defmt::info!` frames below land in the CDBG ring described by `[dbg.cm33]`.
include!("consortium.gen.rs");

// defmt requires the application to define a timestamp source. A monotonic
// counter is enough for the demo; production firmware would read a cycle counter.
defmt::timestamp!("{=u32}", {
    use core::sync::atomic::{AtomicU32, Ordering};
    static COUNT: AtomicU32 = AtomicU32::new(0);
    COUNT.fetch_add(1, Ordering::Relaxed)
});

const RCC_BASE_NS: *mut () = 0x4420_0000 as *mut ();
const TIM2_BASE_NS: *mut () = 0x4000_0000 as *mut ();
const TIM2_IRQ: u16 = 105;
const TIM2_CLOCK_HZ: u32 = 64_000_000;

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let pin_msk = 1u32 << 6;

    let gpio_rst = 0x442b_0028 as *mut u32;

    unsafe { core::ptr::write_volatile(gpio_rst, pin_msk); }

    let signal_addr = 0x20064000 as *mut u32;
    unsafe {
        write_volatile(signal_addr, 1);
    }
    // Reset the CDBG ring on every boot so a warm reset does not leave a stale,
    // valid-looking descriptor behind. No-op when `[dbg.cm33]` is unconfigured.
    consortium_dbg::logger::ConsortiumLogger::init();

    unsafe {
        write_volatile(signal_addr, 2);
    }

    init_time_driver();

    unsafe {
        write_volatile(signal_addr, 3);
    }

    // Bring up MPU + HSEM interrupt, then run the descriptor handshake.
    let connected = match init().connect().await {
        Ok(endpoints) => endpoints,
        Err(_) => {
            defmt::error!("melt-pot: IPC descriptor handshake failed");
            loop {
                cortex_m::asm::wfi();
            }
        }
    };
    let mut sensor = connected.sensor;

    let mut seq: u32 = 0;
    loop {
        let reading = SensorReading {
            temperature_mdc: simulated_temperature(seq),
            seq,
        };

        // Emit a defmt frame into the CDBG ring (decoded by the CA35).
        defmt::info!(
            "sensor seq={=u32} temp_mdc={=i32}",
            reading.seq,
            reading.temperature_mdc
        );

        // Ignore send errors: if the CA35 hasn't consumed the previous slot yet,
        // skip this sample rather than blocking.
        let _ = sensor.send(&reading).await;

        seq = seq.wrapping_add(1);

        Timer::after_secs(1).await;
    }
}

fn init_time_driver() {
    // STM32MP257F CM33 non-secure CMSIS names this TIM2_BASE_NS and TIM2_IRQn.
    // The boot/runtime handoff must leave TIM2's kernel clock at this rate.
    // SAFETY: RCC_BASE_NS is the STM32MP257F non-secure RCC register block.
    unsafe { write_volatile(0x20064000 as *mut u32, 0x10) };
    let rcc = unsafe { consortium_hal_stm32mp2::pac::peripherals::rcc::RCC::from_ptr(RCC_BASE_NS) };
    unsafe { write_volatile(0x20064000 as *mut u32, 0x11) };
    rcc.TIM2CFGR().modify(|w| {
        w.set_TIM2RST(false);
        w.set_TIM2EN(true);
        w.set_TIM2LPEN(true);
    });
    unsafe { write_volatile(0x20064000 as *mut u32, 0x12) };

    // SAFETY: TIM2 is reserved for this demo firmware and clocked above; the
    // IRQ handler below forwards TIM2_IRQn to the HAL time driver.
    unsafe {
        consortium_hal_stm32mp2::timer_driver::init_timer(TIM2_BASE_NS, TIM2_CLOCK_HZ);
        unsafe { write_volatile(0x20064000 as *mut u32, 0x13) };
        consortium_hal_stm32mp2::hal::nvic::set_priority(TIM2_IRQ, 0x80);
        unsafe { write_volatile(0x20064000 as *mut u32, 0x14) };
        consortium_hal_stm32mp2::hal::nvic::enable(TIM2_IRQ);
        unsafe { write_volatile(0x20064000 as *mut u32, 0x15) };
    }
}

#[interrupt]
fn TIM2() {
    consortium_hal_stm32mp2::timer_driver::on_timer_interrupt();
}

/// Sine-like walk between 20 °C and 30 °C for demo purposes.
fn simulated_temperature(seq: u32) -> i32 {
    25_000 + ((seq % 20) as i32 - 10) * 500
}

#[panic_handler]
fn panic(info: &core::panic::PanicInfo) -> ! {
    cortex_m::interrupt::disable();

    let mut current_addr = 0x2006_4000 as *mut u8;
    let end_addr = 0x2006_8000 as *mut u8;

    let prefix = b"[PANIC]";

    for &byte in prefix {
        unsafe {
            write_volatile(current_addr, byte as u8);
            current_addr = current_addr.add(1);
        }
    }

    if let Some(location) = info.location() {
        let file_bytes = location.file().as_bytes();
        let line_count = location.line();

        for &byte in file_bytes {
            unsafe {
                write_volatile(current_addr, byte as u8);
                current_addr = current_addr.add(1);
            }
        }

        if current_addr < end_addr {
            unsafe {
                write_volatile(current_addr, b':' as u8);
                current_addr = current_addr.add(1);
            }
        }

        let mut line_buf = [0u8; 10];
        let mut line_index = 0;
        let mut line = line_count;
        while line > 0 && line_index < line_buf.len() {
            line_buf[line_index] = b'0' + (line % 10) as u8;
            line /= 10;
            line_index += 1;
        }

        for i in (0..line_index).rev() {
            unsafe {
                write_volatile(current_addr, line_buf[i] as u8);
                current_addr = current_addr.add(1);
            }
        }
    }

    if current_addr < end_addr {
        unsafe {
            write_volatile(current_addr, b'\0' as u8);
        }
    }

    loop {
        compiler_fence(core::sync::atomic::Ordering::SeqCst);
        cortex_m::asm::wfi();
    }
}

#[cortex_m_rt::exception]
unsafe fn HardFault(ef: &cortex_m_rt::ExceptionFrame) -> ! {
    cortex_m::interrupt::disable();

    let addr = 0x2006_4000 as *mut u32;

    unsafe { core::ptr::write_volatile(addr, b'H' as u32); }
    unsafe { core::ptr::write_volatile(addr.add(1), b'F' as u32); }
    unsafe { core::ptr::write_volatile(addr.add(2), b'\0' as u32); }

    let pc = ef.pc();
    let pc_bytes = pc.to_le_bytes();
    for (i, &byte) in pc_bytes.iter().enumerate() {
        unsafe { core::ptr::write_volatile(addr.add(3 + i), byte as u32); }
    }

    loop {
        compiler_fence(core::sync::atomic::Ordering::SeqCst);
        cortex_m::asm::wfi();
    }
}
