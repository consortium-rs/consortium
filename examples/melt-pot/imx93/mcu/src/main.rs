//! melt-pot CM33 firmware: streams simulated temperature readings to the CA55
//! over the generated `sensor` IPC transceiver.
//!
//! All of the shared-memory / doorbell / MPU / NVIC / time-driver / peripheral
//! wiring lives in `consortium.gen.rs`, which the `consortium` build pipeline
//! generates from `../Consortium.toml` and this file `include!`s. That module
//! exposes synchronous `init(Config) -> (Peripherals, Channels)`. The firmware
//! constructs drivers from the allowed peripheral singletons and connects each
//! IPC channel independently.
//! The generated `init` also resets the CDBG ring, brings up the Embassy time
//! driver, and installs its `#[interrupt] fn LPIT1()` vector and
//! `defmt::timestamp!`.
//!
//! This is the i.MX93 sibling of `../../imx95/mcu`. The application code is
//! identical; what differs is generated. The CM33 drives MU side B, so the
//! generated bring-up builds `MuDoorbell<Secondary, N>` from the `MUn_MUB`
//! singleton and installs the matching `#[interrupt] fn MUn_B()` vector.

#![no_std]
#![no_main]

use embassy_executor::Spawner;
use embassy_time::Timer;
use melt_pot_shared::SensorReading;
use panic_halt as _;

// Generated by `consortium build`; see the module docs above. Depending on
// `consortium-dbg` with the `logger` feature also registers its defmt sink, so
// the `defmt::info!` frames below land in the CDBG ring described by `[dbg.cm33]`.
include!("consortium.gen.rs");

#[consortium_runtime_mcu::main]
async fn main(_spawner: Spawner) -> Result<(), ConsortiumError> {
    let (p, c) = init(Config::default());
    let mut sensor = ::consortium_ipc_transport_memory::Transceiver::connect(c.SENSOR).await?;

    // The core's owned peripherals, generated from the `[peripheral.*]` entries
    // in `../Consortium.toml` and brought up inside `init()`. Platform setup
    // (A-core / system manager) must leave GPIO2 and LPI2C1 clocked for the CM33.
    //
    // `gpio2` pin 0 is a status heartbeat toggled once per sample. `lpi2c1` is
    // the sensor bus a real driver would read to replace `simulated_temperature`.
    let mut heartbeat = consortium_hal_imx9::gpio::Gpio::new(p.GPIO2)
        .pin(0)
        .into_output(consortium_hal_imx9::gpio::Level::Low);
    let mut _sensor_bus = consortium_hal_imx9::i2c::I2c::new(
        p.LPI2C1,
        LPI2C1_CLOCK_HZ,
        LPI2C1_FREQUENCY,
    );

    let mut seq: u32 = 0;
    loop {
        let reading = SensorReading {
            temperature_mdc: simulated_temperature(seq),
            seq,
        };

        // Emit a defmt frame into the CDBG ring (decoded by the CA55).
        defmt::info!(
            "sensor seq={=u32} temp_mdc={=i32}",
            reading.seq,
            reading.temperature_mdc
        );

        // Ignore send errors: if the CA55 hasn't consumed the previous slot yet,
        // skip this sample rather than blocking.
        let _ = sensor.send(&reading).await;

        // Blink the heartbeat so the board shows liveness between samples.
        heartbeat.toggle();

        seq = seq.wrapping_add(1);

        Timer::after_secs(1).await;
    }
}

/// Sine-like walk between 20 °C and 30 °C for demo purposes.
fn simulated_temperature(seq: u32) -> i32 {
    25_000 + ((seq % 20) as i32 - 10) * 500
}
