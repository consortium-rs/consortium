//! melt-pot CM33 firmware: streams simulated temperature readings to the CA55
//! over the generated `sensor` IPC transceiver.
//!
//! All of the shared-memory / doorbell / MPU / NVIC / time-driver / peripheral
//! wiring lives in `consortium.gen.rs`, which the `consortium` build pipeline
//! generates from `../Consortium.toml` and this file `include!`s. That module
//! exposes synchronous `init(Config) -> (Peripherals, Channels)`. The firmware
//! constructs drivers from the allowed peripheral singletons and connects each
//! IPC channel independently.
//! The generated `init` also resets the CDBG ring, brings up the Embassy time
//! driver, and installs its `#[interrupt] fn LPIT1()` vector and
//! `defmt::timestamp!`.
//!
//! This is the i.MX93 sibling of `../../imx95/mcu`. The application code is
//! identical; what differs is generated. The CM33 drives MU side B, so the
//! generated bring-up builds `MuDoorbell<Secondary, N>` from the `MUn_MUB`
//! singleton and installs the matching `#[interrupt] fn MUn_B()` vector.

#![no_std]
#![no_main]

use core::panic::PanicInfo;

use cortex_m_rt::{ExceptionFrame, exception};
use embassy_executor::Spawner;
use embassy_time::Timer;
use melt_pot_shared::SensorReading;

/// Reports the panic into the CDBG ring, then parks the core.
///
/// The CA55 decodes the frame like any other `defmt` output, so a panic on the
/// CM33 shows up in `defmt-host` instead of as a silent stall.
#[panic_handler]
fn panic(info: &PanicInfo) -> ! {
    cortex_m::interrupt::disable();
    defmt::error!("panic: {}", defmt::Display2Format(info));
    park()
}

/// Reports the faulting context and the fault status registers into the CDBG
/// ring, then parks the core.
///
/// Decoding the result (ARMv8-M ARM, B3.2):
///
/// - `CFSR[15:8]` is the BusFault status. `PRECISERR` (bit 9) with
///   `BFARVALID` (bit 15) means `bfar` is the faulting address and `pc` the
///   faulting instruction; `IMPRECISERR` (bit 10) means a buffered write
///   faulted later and `bfar` is meaningless.
/// - `CFSR[7:0]` is MemManage (`mmfar` valid with `MMARVALID`, bit 7);
///   `CFSR[31:16]` is UsageFault.
/// - `HFSR.FORCED` (bit 30) means one of the above escalated, because those
///   handlers are not enabled.
/// - `SFSR`/`SFAR` report a SecureFault; they read as zero from Non-secure.
#[exception]
unsafe fn HardFault(ef: &ExceptionFrame) -> ! {
    cortex_m::interrupt::disable();

    // SAFETY: these are architecturally defined, always-readable System
    // Control Space registers (ARMv8-M ARM, B3.2); reading them has no side
    // effects, and the core is about to park, so nothing else touches them.
    let (cfsr, hfsr, mmfar, bfar, sfsr, sfar) = unsafe {
        (
            core::ptr::read_volatile(0xE000_ED28 as *const u32),
            core::ptr::read_volatile(0xE000_ED2C as *const u32),
            core::ptr::read_volatile(0xE000_ED34 as *const u32),
            core::ptr::read_volatile(0xE000_ED38 as *const u32),
            core::ptr::read_volatile(0xE000_EDE4 as *const u32),
            core::ptr::read_volatile(0xE000_EDE8 as *const u32),
        )
    };

    defmt::error!(
        "hardfault: pc={=u32:#010x} lr={=u32:#010x} xpsr={=u32:#010x}",
        ef.pc(),
        ef.lr(),
        ef.xpsr()
    );
    defmt::error!(
        "hardfault: r0={=u32:#010x} r1={=u32:#010x} r2={=u32:#010x} r3={=u32:#010x} r12={=u32:#010x}",
        ef.r0(),
        ef.r1(),
        ef.r2(),
        ef.r3(),
        ef.r12()
    );
    defmt::error!(
        "hardfault: cfsr={=u32:#010x} hfsr={=u32:#010x} mmfar={=u32:#010x} bfar={=u32:#010x} sfsr={=u32:#010x} sfar={=u32:#010x}",
        cfsr,
        hfsr,
        mmfar,
        bfar,
        sfsr,
        sfar
    );
    park()
}

/// Sleeps forever with interrupts masked.
fn park() -> ! {
    loop {
        cortex_m::asm::wfi();
    }
}

// Generated by `consortium build`; see the module docs above. Depending on
// `consortium-dbg` with the `logger` feature also registers its defmt sink, so
// the `defmt::info!` frames below land in the CDBG ring described by `[dbg.cm33]`.
include!("consortium.gen.rs");

mod hil;

#[consortium_runtime_mcu::main]
async fn main(spawner: Spawner) -> Result<(), ConsortiumError> {
    let (_p, c) = init(Config::default());
    hil::launched();
    spawner.spawn(hil::monitor().unwrap());

    hil::connecting();
    let mut sensor = ::consortium_ipc_transport_memory::Transceiver::connect(c.SENSOR)
        .await
        .inspect_err(|e| defmt::error!("HIL M6 FAIL Connect returned {}", e))?;
    hil::connected();

    let mut seq: u32 = 0;
    loop {
        let reading = SensorReading {
            temperature_mdc: simulated_temperature(seq),
            seq,
        };

        // Emit a defmt frame into the CDBG ring (decoded by the CA55).
        defmt::info!(
            "sensor seq={=u32} temp_mdc={=i32}",
            reading.seq,
            reading.temperature_mdc
        );

        // Ignore send errors: if the CA55 hasn't consumed the previous slot yet,
        // skip this sample rather than blocking.
        let sent = sensor.send(&reading).await;
        hil::sent(reading.seq, sent.is_ok());

        seq = seq.wrapping_add(1);

        Timer::after_secs(1).await;
    }
}

/// Sine-like walk between 20 °C and 30 °C for demo purposes.
fn simulated_temperature(seq: u32) -> i32 {
    25_000 + ((seq % 20) as i32 - 10) * 500
}
