//! melt-pot CA55 application: receives temperature readings from the CM7 over
//! the generated `sensor` transceiver, runs an OP-TEE threshold check, and
//! serves the verdict to a Cog/WebKit HMI.
//!
//! The UIO bring-up, IPC transceivers, and defmt console live in
//! `consortium.gen.rs`, generated by the `consortium` build pipeline from
//! `../Consortium.toml` and `include!`d below. `init(Config::default())` returns
//! platform resources plus one take-once token per IPC channel; each channel is
//! connected independently when the application is ready for it.

#![cfg(target_os = "linux")]

use std::sync::{Arc, Mutex};

use consortium_hmi_webkit::{Bridge, KioskApp};
use melt_pot_shared::SensorReading;

// Generated by `consortium build`; see the module docs above.
include!("consortium.gen.rs");

// `consortium-builder` injects the `[tee] uuid` as `CONSORTIUM_TEE_UUID` (the
// same value the TA build consumes), so CA and TA always agree. A plain build
// falls back to the placeholder UUID from Consortium.toml.
const TA_UUID: &str = match option_env!("CONSORTIUM_TEE_UUID") {
    Some(uuid) => uuid,
    None => "12345678-1234-1234-1234-123456789012",
};

/// Status shared between the IPC receive task and the HMI bridge.
#[derive(serde::Serialize, serde::Deserialize, Clone)]
struct Status {
    temperature_mdc: i32,
    seq: u32,
    within_limits: bool,
}

#[consortium_runtime_app::main]
async fn main() -> Result<(), ConsortiumError> {
    let (p, c) = init(Config::default())?;
    let sensor = ::consortium_ipc_transport_memory::Transceiver::connect(c.SENSOR).await?;
    let state: Arc<Mutex<Option<Status>>> = Arc::new(Mutex::new(None));
    let handle = tokio::runtime::Handle::current();

    // The receive loop owns the platform resources for its whole lifetime while
    // this thread drives the GLib/WebKit main loop below.
    let state_ipc = Arc::clone(&state);
    tokio::spawn(async move {
        let _p = p;
        let mut sensor = sensor;
        loop {
            match sensor.recv().await {
                Ok(msg) => {
                    let reading: SensorReading = msg.into_inner();
                    let within_limits = tee_check(reading.temperature_mdc);
                    *state_ipc.lock().unwrap() = Some(Status {
                        temperature_mdc: reading.temperature_mdc,
                        seq: reading.seq,
                        within_limits,
                    });
                }
                Err(e) => {
                    eprintln!("melt-pot: ipc recv error: {e}");
                    break;
                }
            }
        }
    });

    // ── HMI bridge ───────────────────────────────────────────────────────────
    let mut bridge = Bridge::new();

    let state_hmi = Arc::clone(&state);
    bridge.handle("get_status", move |_payload| {
        match state_hmi.lock().unwrap().clone() {
            Some(s) => serde_json::to_string(&s).unwrap_or_else(|_| "null".into()),
            None => "null".into(),
        }
    });

    let app = KioskApp::new("melt-pot-imx95", None, None).expect("KioskApp init");
    app.attach_bridge_with_runtime(bridge, handle)
        .expect("bridge attach");
    app.load().expect("HMI load");

    // Run the GLib main loop on this thread (required by WebKit/Cog). The tokio
    // worker threads continue running the IPC receive loop concurrently.
    glib::MainLoop::new(None, false).run();
    Ok(())
}

/// Software safe range, mirroring the TA's `TEMP_LIMIT_LO..=TEMP_LIMIT_HI`.
/// Used as the fallback verdict when OP-TEE is not reachable.
const SOFT_TEMP_RANGE: std::ops::RangeInclusive<i32> = -20_000..=85_000;

/// Ask the TEE whether `temperature_mdc` is within limits, falling back to a
/// software range check when OP-TEE is not reachable (e.g. on a dev host).
fn tee_check(temperature_mdc: i32) -> bool {
    match tee_check_optee(temperature_mdc) {
        Ok(within_limits) => within_limits,
        Err(err) => {
            eprintln!("melt-pot: OP-TEE check unavailable ({err}); using software fallback");
            SOFT_TEMP_RANGE.contains(&temperature_mdc)
        }
    }
}

/// Real OP-TEE invocation: `Context::new` → `open_session(uuid)` → invoke.
fn tee_check_optee(temperature_mdc: i32) -> consortium_tee::TeeResult<bool> {
    use consortium_tee::TeeError;
    use optee_teec::{Context, Uuid};

    let uuid = Uuid::parse_str(TA_UUID).map_err(TeeError::Session)?;
    let mut ctx = Context::new().map_err(TeeError::Context)?;
    let mut session = ctx.open_session(uuid).map_err(TeeError::Session)?;
    melt_pot_imx95_ta::call_check_temperature(&mut session, temperature_mdc)
}
