#!/usr/bin/env python3
"""Generate svd2rust-style interrupt files from chip JSON databases.

Reads `crates/consortium-data/database/chip/<chip>.json` and, for each target,
emits:

  * `<crate>/src/interrupts/<chip>.rs` -- an `enum Interrupt` with one
    explicitly-numbered variant per IRQ, a `cortex_m::interrupt::InterruptNumber`
    impl, and (behind the `rt` feature) the `cortex_m_rt::interrupt` re-export,
    an `interrupt` type alias, and the `__INTERRUPTS` vector table placed in
    `.vector_table.interrupts`.
  * `<crate>/src/interrupts/<chip>.x` -- a `device.x` linker fragment that
    `PROVIDE`s a `DefaultHandler` fallback for every interrupt, matching the
    layout cortex-m-rt's `link.x` expects (`INCLUDE device.x`).

The crate `build.rs` selects the active chip's `.x` fragment and copies it to
`OUT_DIR/device.x` when the `rt` feature is enabled.

Run from the repository root:

    python3 scripts/pac/gen_interrupts.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CHIP_DIR = ROOT / "crates" / "consortium-data" / "database" / "chip"

# (json stem, output stem under `<crate>/src/interrupts/`)
TARGETS = [
    ("stm32mp25_cm33", "crates/consortium-pac-stm32mp2/src/interrupts/stm32mp25"),
    ("stm32mp21_cm33", "crates/consortium-pac-stm32mp2/src/interrupts/stm32mp21"),
    ("mimx95_cm7", "crates/consortium-pac-imx9/src/interrupts/imx95"),
    ("mimx93_cm33", "crates/consortium-pac-imx9/src/interrupts/imx93"),
]


def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def render_rs(chip: dict) -> str:
    name = chip["name"]
    family = chip["family"]
    core = chip["core"]
    irqs = sorted(chip["irqs"], key=lambda i: i["value"])
    by_value = {i["value"]: i for i in irqs}
    count = irqs[-1]["value"] + 1

    out: list[str] = []
    out.append("// Generated by scripts/pac/gen_interrupts.py -- do not edit by hand.")
    out.append(f"// Source: {family} ({core}) interrupt table `{name}`.")
    out.append("#![allow(non_camel_case_types)]")
    out.append("")

    # Interrupt enum.
    out.append(f'#[doc = "Interrupt lines of {family} ({core})."]')
    out.append("#[derive(Copy, Clone, Debug, PartialEq, Eq)]")
    out.append('#[cfg_attr(feature = "defmt", derive(defmt::Format))]')
    out.append("pub enum Interrupt {")
    for irq in irqs:
        desc = irq.get("description")
        if desc:
            out.append(f'    #[doc = "{escape(desc)}"]')
        out.append(f"    {irq['name']} = {irq['value']},")
    out.append("}")
    out.append("")
    out.append(
        "// SAFETY: each variant carries the external interrupt number defined by the"
    )
    out.append("// chip's vendor headers, so `number` returns a valid NVIC line.")
    out.append("unsafe impl cortex_m::interrupt::InterruptNumber for Interrupt {")
    out.append("    #[inline(always)]")
    out.append("    fn number(self) -> u16 {")
    out.append("        self as u16")
    out.append("    }")
    out.append("}")
    out.append("")

    # cortex-m-rt integration.
    out.append(
        "// `#[interrupt]` handler support. The attribute macro (macro namespace)"
    )
    out.append(
        "// and the `Interrupt` alias (type namespace) share the name `interrupt`,"
    )
    out.append(
        "// so the macro's generated `interrupt::NAME;` existence check resolves."
    )
    out.append('#[cfg(feature = "rt")]')
    out.append("pub use cortex_m_rt::interrupt;")
    out.append('#[cfg(feature = "rt")]')
    out.append("pub use self::Interrupt as interrupt;")
    out.append("")
    out.append('#[cfg(feature = "rt")]')
    out.append("#[doc(hidden)]")
    out.append("#[allow(dead_code)]")
    out.append("pub union Vector {")
    out.append('    handler: unsafe extern "C" fn(),')
    out.append("    reserved: usize,")
    out.append("}")
    out.append("")
    out.append('#[cfg(feature = "rt")]')
    out.append('unsafe extern "C" {')
    for irq in irqs:
        out.append(f"    fn {irq['name']}();")
    out.append("}")
    out.append("")
    out.append(
        f'#[doc = "Device-specific interrupt portion of the vector table for {family} ({core})."]'
    )
    out.append('#[cfg(feature = "rt")]')
    out.append("#[doc(hidden)]")
    out.append('#[unsafe(link_section = ".vector_table.interrupts")]')
    out.append("#[unsafe(no_mangle)]")
    out.append(f"pub static __INTERRUPTS: [Vector; {count}] = [")
    for value in range(count):
        irq = by_value.get(value)
        if irq is not None:
            out.append(
                f"    Vector {{ handler: {irq['name']} }}, // {value}: {irq['name']}"
            )
        else:
            out.append(f"    Vector {{ reserved: 0 }}, // {value}: reserved")
    out.append("];")
    out.append("")
    return "\n".join(out)


def render_device_x(chip: dict) -> str:
    family = chip["family"]
    core = chip["core"]
    irqs = sorted(chip["irqs"], key=lambda i: i["value"])
    out: list[str] = []
    out.append(
        f"/* Generated by scripts/pac/gen_interrupts.py -- {family} ({core}). */"
    )
    out.append(
        "/* Weak DefaultHandler fallbacks for interrupts without a `#[interrupt]`. */"
    )
    for irq in irqs:
        out.append(f"PROVIDE({irq['name']} = DefaultHandler);")
    out.append("")
    return "\n".join(out)


def main() -> None:
    for stem, out_rel in TARGETS:
        chip = json.loads((CHIP_DIR / f"{stem}.json").read_text())
        rs = ROOT / f"{out_rel}.rs"
        dx = ROOT / f"{out_rel}.x"
        rs.parent.mkdir(parents=True, exist_ok=True)
        rs.write_text(render_rs(chip))
        dx.write_text(render_device_x(chip))
        print(f"wrote {out_rel}.rs / {out_rel}.x ({len(chip['irqs'])} irqs)")


if __name__ == "__main__":
    main()
