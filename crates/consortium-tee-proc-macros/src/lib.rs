#[proc_macro]
/// Input:
///
/// ```no-run
/// tee_service! {
///   (optional) context ContextStruct
///   commands { function_a, function_b }
/// }
/// ```
///
/// Generates:
/// 1. `Command` enum with PascalCase variants and discriminants starting at 0, plus a
///    `#[default] Unknown` catch-all at the end.
/// 2. `invoke_command` (annotated `#[invoke_command]`) that dispatches to each
///    `function_*_dispatched` wrapper generated by `#[tee_command]`.
pub fn tee_service(input: TokenStream) -> TokenStream {
    let TeeServiceInput { commands, context } = parse_macro_input!(input as TeeServiceInput);

    let variant_idents: Vec<Ident> = commands
        .iter()
        .map(|cmd| Ident::new(&cmd.to_string().to_pascal_case(), cmd.span()))
        .collect();

    let discriminants: Vec<_> = (0u64..)
        .take(commands.len())
        .map(|n| syn::LitInt::new(&n.to_string(), Span::call_site()))
        .collect();

    let unknown_discriminant = syn::LitInt::new(&commands.len().to_string(), Span::call_site());

    let command_enum = quote! {
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
        #[repr(u64)]
        pub enum Command {
            #(#variant_idents = #discriminants,)*
            #[default]
            Unknown = #unknown_discriminant,
        }
    };

    let dispatch_fns: Vec<Ident> = commands
        .iter()
        .map(|cmd| Ident::new(&format!("{}_dispatched", cmd), cmd.span()))
        .collect();

    let invoke_fn = if let Some(ctx_ident) = context {
        quote! {
            #[invoke_command]
            pub(crate) fn invoke_command(
                ctx: &mut #ctx_ident,
                cmd: Command,
                params: &mut optee_utee::Parameters,
            ) -> Result<()> {
                match cmd {
                    #(Command::#variant_idents => #dispatch_fns(ctx, params),)*
                    Command::Unknown => Err(Error::UnknownCommand),
                }
            }
        }
    } else {
        quote! {
            #[invoke_command]
            pub(crate) fn invoke_command(
                cmd: Command,
                params: &mut optee_utee::Parameters,
            ) -> Result<()> {
                match cmd {
                    #(Command::#variant_idents => #dispatch_fns(params),)*
                    Command::Unknown => Err(Error::UnknownCommand),
                }
            }
        }
    };

    quote! {
        #command_enum
        #invoke_fn
    }
    .into()
}

/// Generates two companion functions for a TA command handler:
///
/// **`function_name_dispatched`** (TA side) — unpacks `optee_utee::Parameters` into typed
/// arguments, calls the original function, and if it returns a non-`()` value, flushes that
/// value back into the next available output parameter slot before returning `Ok(())`.
///
/// **`call_function_name`** (CA side, `#[cfg(feature = "ca")]`) — packs arguments into
/// parameters, allocates an extra `ValueOutput` slot when the function has a return value,
/// calls `invoke_command`, then reads the output slot back and returns
/// `consortium_tee::TeeResult<T>`.
///
/// The original function body is emitted unchanged.
///
/// # Parameter type support
/// | Rust type    | TEE encoding                        |
/// |--------------|-------------------------------------|
/// | `u32`        | `ValueInput` / `ValueInout` — `a`   |
/// | `u64`        | `ValueInput` — `(a << 32) \| b`     |
/// | `bool`       | `ValueInput` — `a` (0/1)            |
/// | `&[u8]`      | `MemrefInput`                       |
/// | `&mut [u8]`  | `MemrefInout`                       |
///
/// Return values (`u32`, `u64`, `bool`) are flushed via `ValueOutput`/`ValueInout`.
#[proc_macro_attribute]
pub fn tee_command(_attr: TokenStream, item: TokenStream) -> TokenStream {
    let input = parse_macro_input!(item as ItemFn);
    let fn_name = &input.sig.ident;
    let dispatched_name = Ident::new(&format!("{}_dispatched", fn_name), fn_name.span());
    let call_name = Ident::new(&format!("call_{}", fn_name), fn_name.span());

    let parameters: Vec<&PatType> = input
        .sig
        .inputs
        .iter()
        .filter_map(|arg| {
            if let syn::FnArg::Typed(pt) = arg {
                Some(pt)
            } else {
                None
            }
        })
        .collect();

    // First typed param is treated as context if it's `&mut SomeIdent` (not a slice).
    let (ctx_param, tee_params) = match parameters.first() {
        Some(p) if is_context_ref(&p.ty) => (Some(*p), &parameters[1..]),
        _ => (None, &parameters[..]),
    };

    // Return-type analysis.
    let output_ty: Option<&syn::Type> = get_output_type(&input.sig.output);
    let has_output = output_ty.is_some();
    let ret_is_result = is_result_returning(&input.sig.output);

    // ── TA side: unpack stmts ────────────────────────────────────────────────
    let mut slot_index = 0usize;
    let mut unpack_stmts = vec![];
    let mut dispatch_call_args = vec![];

    if let Some(ctx) = ctx_param {
        let pat = &ctx.pat;
        dispatch_call_args.push(quote! { #pat });
    }

    for param in tee_params {
        let pat = &param.pat;
        let ty = &param.ty;
        let (stmt, next) = gen_unpack(pat, ty, slot_index);
        unpack_stmts.push(stmt);
        dispatch_call_args.push(quote! { #pat });
        slot_index = next;
    }

    // Output slot index (immediately after the last input slot).
    let output_slot = slot_index;

    // ── TA side: call + optional flush ──────────────────────────────────────
    let call_and_flush = if let Some(out_ty) = output_ty {
        let flush = gen_flush_ta(output_slot, out_ty);
        if ret_is_result {
            quote! {
                let __ret_val = #fn_name(#(#dispatch_call_args),*)?;
                // Flush return value into output parameter slot.
                #flush
                Ok(())
            }
        } else {
            quote! {
                let __ret_val = #fn_name(#(#dispatch_call_args),*);
                // Flush return value into output parameter slot.
                #flush
                Ok(())
            }
        }
    } else {
        quote! { #fn_name(#(#dispatch_call_args),*) }
    };

    // Use `_params` only when nothing reads/writes params at all.
    let param_binding = if !tee_params.is_empty() || has_output {
        quote! { params }
    } else {
        quote! { _params }
    };

    // ── TA dispatched fn ────────────────────────────────────────────────────
    let dispatched_fn = if let Some(ctx) = ctx_param {
        let ctx_pat = &ctx.pat;
        let ctx_ty = &ctx.ty;
        quote! {
            fn #dispatched_name(#ctx_pat: #ctx_ty, #param_binding: &mut optee_utee::Parameters) -> Result<()> {
                #(#unpack_stmts)*
                #call_and_flush
            }
        }
    } else {
        quote! {
            fn #dispatched_name(#param_binding: &mut optee_utee::Parameters) -> Result<()> {
                #(#unpack_stmts)*
                #call_and_flush
            }
        }
    };

    // ── CA side: pack stmts ─────────────────────────────────────────────────
    let mut pack_stmts = vec![];
    let mut ca_sig_args = vec![];
    let mut new_params_args = vec![];

    for (i, param) in tee_params.iter().enumerate() {
        let pat = &param.pat;
        let ty = &param.ty;
        let slot_ident = Ident::new(&format!("_p{}", i), Span::call_site());
        ca_sig_args.push(quote! { #pat: #ty });
        pack_stmts.push(gen_pack_ca(&slot_ident, pat, ty));
        new_params_args.push(quote! { #slot_ident });
    }

    // Add ValueOutput / MemrefOutput slot for the return value, if needed.
    if has_output {
        let out_ty = output_ty.unwrap();
        let out_slot = tee_params.len();
        let slot_ident = Ident::new(&format!("_p{}", out_slot), Span::call_site());
        pack_stmts.push(gen_output_pack_ca(&slot_ident, out_ty, out_slot));
        new_params_args.push(quote! { #slot_ident });
    }

    // Parameters::new always takes exactly 4 args.
    while new_params_args.len() < 4 {
        new_params_args.push(quote! { optee_utee::ParamNone });
    }

    let command_variant = Ident::new(&fn_name.to_string().to_pascal_case(), fn_name.span());

    // ── CA fn ───────────────────────────────────────────────────────────────
    let ca_fn = if has_output {
        let out_ty = output_ty.unwrap();
        let read_back = gen_output_read_ca(tee_params.len(), out_ty);
        quote! {
            #[cfg(feature = "ca")]
            fn #call_name(#(#ca_sig_args),*) -> consortium_tee::TeeResult<#out_ty> {
                #(#pack_stmts)*
                let mut _params = optee_utee::Parameters::new(#(#new_params_args),*);
                invoke_command(Command::#command_variant, &mut _params)?;
                Ok(#read_back)
            }
        }
    } else {
        quote! {
            #[cfg(feature = "ca")]
            fn #call_name(#(#ca_sig_args),*) -> consortium_tee::TeeResult<()> {
                #(#pack_stmts)*
                invoke_command(
                    Command::#command_variant,
                    &mut optee_utee::Parameters::new(#(#new_params_args),*),
                )
            }
        }
    };

    quote! {
        #input
        #dispatched_fn
        #ca_fn
    }
    .into()
}

// ── Type helpers ─────────────────────────────────────────────────────────────

/// If the return type is `Result<T>` and `T` is not `()`, returns `Some(T)`.
/// If the return type is `T` (non-`Result`) and T is not `()`, returns `Some(T)`.
/// Otherwise `None` — no output parameter is needed.
fn get_output_type(ret: &syn::ReturnType) -> Option<&syn::Type> {
    let ty = match ret {
        syn::ReturnType::Default => return None,
        syn::ReturnType::Type(_, ty) => ty.as_ref(),
    };
    if let Some(inner) = extract_result_inner(ty) {
        if !is_unit_type(inner) {
            return Some(inner);
        }
        return None;
    }
    if !is_unit_type(ty) {
        Some(ty)
    } else {
        None
    }
}

/// Returns `true` when the declared return type wraps `Result<…>`.
fn is_result_returning(ret: &syn::ReturnType) -> bool {
    match ret {
        syn::ReturnType::Type(_, ty) => extract_result_inner(ty.as_ref()).is_some(),
        _ => false,
    }
}

/// Extracts `T` from `Result<T>` (last segment named `Result` with angle-bracket args).
fn extract_result_inner(ty: &syn::Type) -> Option<&syn::Type> {
    if let syn::Type::Path(tp) = ty {
        let seg = tp.path.segments.last()?;
        if seg.ident != "Result" {
            return None;
        }
        if let syn::PathArguments::AngleBracketed(ab) = &seg.arguments {
            if let Some(syn::GenericArgument::Type(inner)) = ab.args.first() {
                return Some(inner);
            }
        }
    }
    None
}

fn is_unit_type(ty: &syn::Type) -> bool {
    matches!(ty, syn::Type::Tuple(t) if t.elems.is_empty())
}

fn is_primitive(ty: &syn::Type, name: &str) -> bool {
    if let syn::Type::Path(tp) = ty {
        tp.qself.is_none() && tp.path.is_ident(name)
    } else {
        false
    }
}

fn is_vec_u8(ty: &syn::Type) -> bool {
    if let syn::Type::Path(tp) = ty {
        if tp.qself.is_none() {
            if let Some(seg) = tp.path.segments.last() {
                if seg.ident == "Vec" {
                    if let syn::PathArguments::AngleBracketed(ab) = &seg.arguments {
                        if let Some(syn::GenericArgument::Type(inner)) = ab.args.first() {
                            return is_primitive(inner, "u8");
                        }
                    }
                }
            }
        }
    }
    false
}

fn is_slice_ref(ty: &syn::Type, mutable: bool) -> bool {
    if let syn::Type::Reference(r) = ty {
        r.mutability.is_some() == mutable && matches!(*r.elem, syn::Type::Slice(_))
    } else {
        false
    }
}

/// Returns `true` if `ty` is `&mut SomeIdent` — i.e., a mutable reference to a named
/// type (not a slice), which we treat as the implicit context parameter.
fn is_context_ref(ty: &syn::Type) -> bool {
    if let syn::Type::Reference(r) = ty {
        r.mutability.is_some() && matches!(*r.elem, syn::Type::Path(_))
    } else {
        false
    }
}

// ── TA-side unpack / flush code generation ───────────────────────────────────

fn gen_unpack(
    pat: &syn::Pat,
    ty: &syn::Type,
    slot: usize,
) -> (proc_macro2::TokenStream, usize) {
    if slot >= 4 {
        return (
            quote! { compile_error!("Too many parameters: TEE only supports up to 4"); },
            slot,
        );
    }
    let s = quote::format_ident!("param_{}", slot);
    let stmt = if is_primitive(ty, "bool") {
        quote! { let #pat: bool = params.#s().as_value().a() != 0; }
    } else if is_primitive(ty, "u32") {
        quote! { let #pat: u32 = params.#s().as_value().a(); }
    } else if is_slice_ref(ty, false) {
        quote! { let #pat: &[u8] = params.#s().as_memref().buffer(); }
    } else if is_slice_ref(ty, true) {
        quote! { let #pat: &mut [u8] = params.#s().as_memref_mut().buffer(); }
    } else {
        quote! { compile_error!("Unsupported TEE parameter type"); }
    };
    (stmt, slot + 1)
}

/// Emits statements that write `__ret_val` into the output parameter slot at `slot`.
/// Called after the original function returns on the TA side (the "flush" step).
fn gen_flush_ta(slot: usize, ty: &syn::Type) -> proc_macro2::TokenStream {
    if slot >= 4 {
        return quote! { compile_error!("Too many parameters: no room for the output slot (TEE max 4)"); };
    }
    let s = quote::format_ident!("param_{}", slot);
    if is_primitive(ty, "u32") {
        quote! { params.#s().as_value_mut().set_a(__ret_val); }
    } else if is_primitive(ty, "u64") {
        quote! {
            params.#s().as_value_mut().set_a((__ret_val >> 32) as u32);
            params.#s().as_value_mut().set_b(__ret_val as u32);
        }
    } else if is_primitive(ty, "bool") {
        quote! { params.#s().as_value_mut().set_a(__ret_val as u32); }
    } else if is_vec_u8(ty) {
        quote! {
            {
                let __out = params.#s().as_memref_mut();
                __out.buffer()[..__ret_val.len()].copy_from_slice(&__ret_val);
            }
        }
    } else {
        quote! { compile_error!("Unsupported TEE return type for output parameter (supported: u32, u64, bool, Vec<u8>)"); }
    }
}

// ── CA-side pack / read-back code generation ─────────────────────────────────

fn gen_pack_ca(
    slot_ident: &Ident,
    pat: &syn::Pat,
    ty: &syn::Type,
) -> proc_macro2::TokenStream {
    if is_primitive(ty, "bool") {
        quote! { let #slot_ident = ParamValue::new(#pat as u32, 0, ParamType::ValueInput); }
    } else if is_primitive(ty, "u32") {
        quote! { let #slot_ident = ParamValue::new(#pat, 0, ParamType::ValueInput); }
    } else if is_slice_ref(ty, false) {
        quote! { let #slot_ident = ParamMemref::new(#pat, ParamType::MemrefInput); }
    } else if is_slice_ref(ty, true) {
        quote! { let #slot_ident = ParamMemref::new(#pat, ParamType::MemrefInout); }
    } else {
        quote! { compile_error!("Unsupported TEE parameter type"); }
    }
}

/// Emits the declaration(s) that reserve a slot for the return value on the CA side.
/// For value types this is a single `ParamValue::new(0, 0, ValueOutput)`.
/// For `Vec<u8>` this is a pre-allocated buffer plus a `ParamMemref::new(…, MemrefOutput)`.
/// `slot` is used only to derive a unique buffer ident for the `Vec<u8>` case.
fn gen_output_pack_ca(slot_ident: &Ident, ty: &syn::Type, slot: usize) -> proc_macro2::TokenStream {
    if is_primitive(ty, "u32") || is_primitive(ty, "u64") || is_primitive(ty, "bool") {
        quote! { let #slot_ident = ParamValue::new(0, 0, ParamType::ValueOutput); }
    } else if is_vec_u8(ty) {
        let buf_ident = Ident::new(&format!("__out_buf_{}", slot), Span::call_site());
        quote! {
            let mut #buf_ident = vec![0u8; 4096];
            let #slot_ident = ParamMemref::new(&mut #buf_ident, ParamType::MemrefOutput);
        }
    } else {
        quote! { compile_error!("Unsupported TEE return type for output parameter (supported: u32, u64, bool, Vec<u8>)"); }
    }
}

/// Emits the expression that reads the return value back from `_params` after
/// `invoke_command` completes on the CA side.
fn gen_output_read_ca(slot: usize, ty: &syn::Type) -> proc_macro2::TokenStream {
    let s = quote::format_ident!("param_{}", slot);
    if is_primitive(ty, "u32") {
        quote! { _params.#s().as_value().a() }
    } else if is_primitive(ty, "u64") {
        quote! {
            ((_params.#s().as_value().a() as u64) << 32)
                | (_params.#s().as_value().b() as u64)
        }
    } else if is_primitive(ty, "bool") {
        quote! { _params.#s().as_value().a() != 0 }
    } else if is_vec_u8(ty) {
        // The TA updates the memref's size to the number of bytes written.
        quote! {
            {
                let __m = _params.#s().as_memref();
                __m.buffer()[..__m.size()].to_vec()
            }
        }
    } else {
        quote! { compile_error!("Unsupported TEE return type") }
    }
}
