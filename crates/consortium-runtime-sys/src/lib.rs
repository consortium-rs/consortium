//! Raw FFI bindings to the remoteproc firmware resource-table layout.
//!
//! The types here are generated by `bindgen` from the vendored
//! `include/rsc_table.h` (the Texas Instruments/Google resource-table
//! definitions used by Linux remoteproc). They mirror the on-wire `.resource_table`
//! ELF-section layout that a Linux host parses when booting a coprocessor:
//! [`ResourceTable`], [`FwRscHdr`], [`FwRscCarveout`], [`FwRscDevmem`],
//! [`FwRscTrace`], [`FwRscVdev`], and [`FwRscVdevVring`], plus the
//! [`FwResourceType`] discriminants.
//!
//! This is a `-sys` crate: it exposes the C ABI unchanged. Safe, ergonomic
//! wrappers belong in the consuming runtime crates.

// Bindgen output does not follow Rust naming conventions and includes structs
// that firmware may not reference in every build.
#![allow(
    non_upper_case_globals,
    non_camel_case_types,
    non_snake_case,
    dead_code
)]
// The bindgen `__IncompleteArrayField` helper (flexible-array members) defines
// `unsafe fn`s whose bodies call unsafe slice constructors without an inner
// `unsafe` block. That is generated code we do not edit.
#![allow(unsafe_op_in_unsafe_fn)]

include!(concat!(env!("OUT_DIR"), "/bindings.rs"));
