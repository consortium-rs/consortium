::consortium_ipc_transport_memory::channels!(LP);
::consortium_ipc_transport_memory::impl_channel!(
    LP, ::consortium_ipc::Secondary, ::consortium_ipc_doorbell_mu::MuDoorbell <
    ::consortium_ipc::Secondary, 1usize >,
    ::consortium_shared_memory::regions::UncachedRegion, crate ::shared::PowerControl,
    crate ::shared::LowPowerData, ::consortium_codec::PostcardCodec, 5u8, 4u8, 128usize,
);
#[cfg(target_arch = "arm")]
fn __consortium_install_channels() {
    ::consortium_ipc_transport_memory::install::<
        channels::LP,
    >({
        // SAFETY: automatically generated by Consortium after matching with database
        let region = unsafe {
            ::consortium_shared_memory::regions::UncachedRegion::new(
                (541605888usize) as *mut u8,
                16384usize,
            )
        };
        // SAFETY: the base is the UIO-mapped doorbell register window,
        // resolved from the validated Consortium hardware database.
        let doorbell = unsafe {
            ::consortium_ipc_doorbell_mu::MuDoorbell::<
                ::consortium_ipc::Secondary,
                1usize,
            >::new_mapped(1143078912usize)
        };
        // SAFETY: doorbell channel is verified to be valid in the config.
        let chan_tx = unsafe { ::consortium_ipc::Chan::new_unchecked(5u8) };
        // SAFETY: doorbell channel is verified to be valid in the config.
        let chan_rx = unsafe { ::consortium_ipc::Chan::new_unchecked(4u8) };
        // SAFETY: the base is offset 0x00 of the validated shared-memory
        // region, and the channels/doorbell/region are this side's.
        unsafe {
            ::consortium_ipc_transport_memory::SharedMemoryTransport::<
                ::consortium_ipc::Secondary,
                _,
                _,
            >::new(chan_tx, chan_rx, doorbell, region, (541605888usize) as *mut u8)
        }
    });
}
