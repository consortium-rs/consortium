/// Interrupt vectors for this endpoint's generated bring-up.
#[cfg(target_arch = "arm")]
mod __consortium_vectors {
    use ::consortium_hal_imx9::interrupt;
    #[::consortium_hal_imx9::interrupt]
    fn LPIT1() {
        ::consortium_hal_imx9::timer_driver::on_timer_interrupt();
    }
    const _: () = ::core::assert!(
        ::consortium_hal_imx9::Interrupt::MU1_B as u16 == 22u16,
        "MU1_B is interrupt 22 in this core's Consortium chip map but not in the chip PAC's interrupt table; the generated vector and the NVIC enable would refer to different lines"
    );
    #[::consortium_hal_imx9::interrupt]
    fn MU1_B() {
        ::consortium_ipc_doorbell_mu::notify_gi_interrupt::<
            ::consortium_ipc::Secondary,
            1usize,
        >();
    }
    const _: () = ::core::assert!(
        ::consortium_hal_imx9::Interrupt::MU2_B as u16 == 24u16,
        "MU2_B is interrupt 24 in this core's Consortium chip map but not in the chip PAC's interrupt table; the generated vector and the NVIC enable would refer to different lines"
    );
    #[::consortium_hal_imx9::interrupt]
    fn MU2_B() {
        ::consortium_ipc_doorbell_mu::notify_gi_interrupt::<
            ::consortium_ipc::Secondary,
            2usize,
        >();
    }
    const _: () = ::core::assert!(
        ::consortium_hal_imx9::Interrupt::LPI2C1 as u16 == 13u16,
        "LPI2C1 is interrupt 13 in this core's Consortium chip map but not in the chip PAC's interrupt table; the generated vector and the NVIC enable would refer to different lines"
    );
    #[::consortium_hal_imx9::interrupt]
    fn LPI2C1() {
        ::consortium_hal_imx9::i2c::on_interrupt::<
            ::consortium_hal_imx9::peripherals::LPI2C1,
        >();
    }
}
/// Runtime bring-up policy. Enabled manifest steps default on.
#[cfg(target_arch = "arm")]
#[non_exhaustive]
pub struct Config {
    pub logger: bool,
    pub mpu: bool,
    pub nvic: bool,
    pub time_driver: bool,
}
#[cfg(target_arch = "arm")]
impl ::core::default::Default for Config {
    fn default() -> Self {
        Self {
            logger: true,
            mpu: true,
            nvic: true,
            time_driver: true,
        }
    }
}
/// Brings up synchronous platform resources and installs each
/// unconnected IPC transport into its generated endpoint state.
#[cfg(target_arch = "arm")]
fn init(config: Config) -> (Peripherals, Channels) {
    if config.logger {
        ::consortium_dbg::logger::ConsortiumLogger::init();
    }
    ::consortium_runtime_mcu::log::trace!(
        "consortium controller init: mpu/nvic bring-up"
    );
    // SAFETY: `init` runs once during controller bring-up, in
    // privileged mode, before any other code touches the MPU or
    // cache-control peripherals.
    let mut __core = unsafe { ::cortex_m::Peripherals::steal() };
    if config.mpu {
        // SAFETY: `init` holds exclusive privileged MPU access during
        // bring-up; `base`/`size` are this core's validated shared
        // region from the Consortium hardware layout.
        unsafe {
            ::consortium_runtime_mcu::mpu::disable_cache(
                &mut __core.MPU,
                0u8,
                541589504u32,
                16384u32,
            );
            ::consortium_runtime_mcu::log::trace!(
                "consortium controller init: MPU carveout {} base={:#010x} size={:#010x}",
                0u8, 541589504u32, 16384u32
            );
        }
        // SAFETY: `init` holds exclusive privileged MPU access during
        // bring-up; `base`/`size` are this core's validated shared
        // region from the Consortium hardware layout.
        unsafe {
            ::consortium_runtime_mcu::mpu::disable_cache(
                &mut __core.MPU,
                1u8,
                541622272u32,
                16384u32,
            );
            ::consortium_runtime_mcu::log::trace!(
                "consortium controller init: MPU carveout {} base={:#010x} size={:#010x}",
                1u8, 541622272u32, 16384u32
            );
        }
    }
    if config.nvic {
        ::consortium_hal_imx9::hal::nvic::unpend(
            ::consortium_hal_imx9::Interrupt::MU1_B,
        );
        // SAFETY: the interrupt comes from the validated Consortium
        // hardware database for this visible core, and the application
        // owns the matching vector.
        unsafe {
            ::consortium_hal_imx9::hal::nvic::set_priority(
                ::consortium_hal_imx9::Interrupt::MU1_B,
                0x80u8,
            );
            ::consortium_hal_imx9::hal::nvic::enable(
                ::consortium_hal_imx9::Interrupt::MU1_B,
            );
        }
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: NVIC enabled {} at priority 0x80 (id={})",
            "MU1_B", 22u32
        );
        ::consortium_hal_imx9::hal::nvic::unpend(
            ::consortium_hal_imx9::Interrupt::MU2_B,
        );
        // SAFETY: the interrupt comes from the validated Consortium
        // hardware database for this visible core, and the application
        // owns the matching vector.
        unsafe {
            ::consortium_hal_imx9::hal::nvic::set_priority(
                ::consortium_hal_imx9::Interrupt::MU2_B,
                0x80u8,
            );
            ::consortium_hal_imx9::hal::nvic::enable(
                ::consortium_hal_imx9::Interrupt::MU2_B,
            );
        }
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: NVIC enabled {} at priority 0x80 (id={})",
            "MU2_B", 24u32
        );
        // SAFETY: the interrupt comes from the validated chip map and
        // its generated handler is installed above.
        unsafe {
            ::consortium_hal_imx9::hal::nvic::set_priority(
                ::consortium_hal_imx9::Interrupt::LPI2C1,
                0x80u8,
            );
            ::consortium_hal_imx9::hal::nvic::enable(
                ::consortium_hal_imx9::Interrupt::LPI2C1,
            );
        }
    }
    ::consortium_runtime_mcu::log::trace!("before chip init");
    let __p = ::consortium_hal_imx9::init();
    ::consortium_runtime_mcu::log::trace!("after chip init");
    if config.time_driver {
        ::consortium_hal_imx9::timer_driver::bringup(__p.LPIT1);
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: time driver up"
        );
    }
    __consortium_install_channels(__p.MU1_MUB, __p.MU2_MUB);
    let channels = Channels::take();
    let peripherals = Peripherals {
        GPIO2: __p.GPIO2,
        LPI2C1: __p.LPI2C1,
    };
    ::consortium_runtime_mcu::log::trace!("consortium controller init: resources ready");
    (peripherals, channels)
}
/// Error union suitable for `#[consortium_runtime_mcu::main]`.
#[cfg(target_arch = "arm")]
#[cfg_attr(target_os = "none", derive(Debug, defmt::Format))]
#[cfg_attr(not(target_os = "none"), derive(Debug))]
#[allow(dead_code)]
enum ConsortiumError {
    Connect(::consortium_ipc_transport_memory::ConnectError),
}
#[cfg(target_arch = "arm")]
impl ::core::convert::From<::consortium_ipc_transport_memory::ConnectError>
for ConsortiumError {
    fn from(e: ::consortium_ipc_transport_memory::ConnectError) -> Self {
        Self::Connect(e)
    }
}
