#![allow(dead_code, unused, unused_unsafe, non_snake_case)]

mod shared {
    #[derive(::serde::Serialize, ::serde::Deserialize)]
    pub struct MotionControl {
        pub _v: u32,
    }
    #[derive(::rkyv::Archive, ::rkyv::Serialize)]
    pub struct PowerMode {
        pub _v: u32,
    }
    #[derive(::rkyv::Archive, ::rkyv::Serialize)]
    pub struct PowerStatus {
        pub _v: u32,
    }
    #[derive(::serde::Serialize, ::serde::Deserialize)]
    pub struct SensorData {
        pub _v: u32,
    }
}

/// Descriptor-handshake failure, with the doorbell-specific payload
/// erased so a single error type spans transceivers that use
/// different doorbells. `no_std`-safe (no `alloc`).
#[derive(Debug)]
enum ConsortiumConnectError {
    /// The descriptor header/channel table was invalid or never reached
    /// the ready state.
    Descriptor(::consortium_ipc_transport_memory::DescriptorError),
    /// The doorbell signal failed during the handshake.
    Doorbell,
    /// Any other transport error during the handshake.
    Other,
}
/// IPC endpoints that have been *constructed* but not yet connected.
/// Call [`connect`](IpcMemoryEndpoints::connect) to run the descriptor
/// handshake and obtain usable transceivers.
struct IpcMemoryEndpoints {
    sensor: ::consortium_ipc_transport_memory::SharedMemoryTransport<
        ::consortium_ipc::Secondary,
        ::consortium_ipc_doorbell_hsem::HsemDoorbell<
            ::consortium_ipc::Secondary,
            1usize,
        >,
        ::consortium_shared_memory::regions::SramRegion,
    >,
}
static mut SENSOR_RX_BUF: [u8; 128usize] = [0u8; 128usize];
static mut SENSOR_TX_BUF: [u8; 128usize] = [0u8; 128usize];
/// Connected IPC endpoints: each field is a ready-to-use transceiver.
struct IpcMemoryEndpointsConnected {
    sensor: ::consortium_ipc::Transceiver<
        crate::shared::MotionControl,
        crate::shared::SensorData,
        ::consortium_ipc_transport_memory::SharedMemoryTransportTx<
            ::consortium_ipc_transport_memory::Secondary,
            ::consortium_ipc_doorbell_hsem::HsemDoorbell<
                ::consortium_ipc::Secondary,
                1usize,
            >,
            ::consortium_shared_memory::regions::SramRegion,
        >,
        ::consortium_ipc_transport_memory::SharedMemoryTransportRx<
            ::consortium_ipc_transport_memory::Secondary,
            ::consortium_ipc_doorbell_hsem::HsemDoorbell<
                ::consortium_ipc::Secondary,
                1usize,
            >,
            ::consortium_shared_memory::regions::SramRegion,
        >,
        ::consortium_codec::PostcardCodec,
    >,
}
impl IpcMemoryEndpoints {
    fn new() -> Self {
        Self {
            sensor: {
                // SAFETY: automatically generated by Consortium after matching with database
                let region = unsafe {
                    ::consortium_shared_memory::regions::SramRegion::new(
                        (541065216usize) as *mut u8,
                        16384usize,
                    )
                };
                // SAFETY: the base is the UIO-mapped doorbell register window,
                // resolved from the validated Consortium hardware database.
                let doorbell = unsafe {
                    ::consortium_ipc_doorbell_hsem::HsemDoorbell::<
                        ::consortium_ipc::Secondary,
                        1usize,
                    >::new(1176764416usize)
                };
                // SAFETY: doorbell channel is verified to be valid in the config.
                let chan_tx = unsafe { ::consortium_ipc::Chan::new_unchecked(1u8) };
                // SAFETY: doorbell channel is verified to be valid in the config.
                let chan_rx = unsafe { ::consortium_ipc::Chan::new_unchecked(0u8) };
                // SAFETY: the base is offset 0x00 of the validated shared-memory
                // region, and the channels/doorbell/region are this side's.
                unsafe {
                    ::consortium_ipc_transport_memory::SharedMemoryTransport::<
                        ::consortium_ipc::Secondary,
                        _,
                        _,
                    >::new(
                        chan_tx,
                        chan_rx,
                        doorbell,
                        region,
                        (541065216usize) as *mut u8,
                    )
                }
            },
        }
    }
    /// Runs the descriptor handshake for every transceiver and returns
    /// the connected endpoints. Each transceiver's primary side writes
    /// and the secondary side acks the descriptor before any traffic.
    async fn connect(
        self,
    ) -> ::core::result::Result<IpcMemoryEndpointsConnected, ConsortiumConnectError> {
        ::core::result::Result::Ok(IpcMemoryEndpointsConnected {
            sensor: {
                let transport = self.sensor;
                let (chan_tx, chan_rx) = transport.channels();
                // SAFETY: base covers the descriptor; this side is Secondary, so it
                // validates and acks the primary-written descriptor.
                unsafe {
                    <::consortium_ipc_transport_memory::SharedMemoryTransport<
                        ::consortium_ipc::Secondary,
                        ::consortium_ipc_doorbell_hsem::HsemDoorbell<
                            ::consortium_ipc::Secondary,
                            1usize,
                        >,
                        ::consortium_shared_memory::regions::SramRegion,
                    >>::descriptor_ack(
                            transport.base(),
                            2usize,
                            128usize,
                            transport.doorbell(),
                            chan_rx,
                            chan_tx,
                        )
                        .await
                }
                    .map_err(|__e| match __e {
                        ::consortium_ipc_transport_memory::Error::Descriptor(__d) => {
                            ConsortiumConnectError::Descriptor(__d)
                        }
                        ::consortium_ipc_transport_memory::Error::Doorbell(_) => {
                            ConsortiumConnectError::Doorbell
                        }
                        _ => ConsortiumConnectError::Other,
                    })?;
                let (t_tx, t_rx) = transport.split();
                let channel_tx = ::consortium_ipc::Channel::<
                    ::consortium_ipc::Tx,
                    crate::shared::MotionControl,
                    _,
                    ::consortium_codec::PostcardCodec,
                >::new(
                    chan_tx,
                    t_tx,
                    {
                        // SAFETY: module-level static scratch buffer, borrowed once
                        // during initialization and never aliased afterwards.
                        unsafe { &mut *::core::ptr::addr_of_mut!(SENSOR_RX_BUF) }
                    },
                );
                let channel_rx = ::consortium_ipc::Channel::<
                    ::consortium_ipc::Rx,
                    crate::shared::SensorData,
                    _,
                    ::consortium_codec::PostcardCodec,
                >::new(
                    chan_rx,
                    t_rx,
                    {
                        // SAFETY: module-level static scratch buffer, borrowed once
                        // during initialization and never aliased afterwards.
                        unsafe { &mut *::core::ptr::addr_of_mut!(SENSOR_TX_BUF) }
                    },
                );
                ::consortium_ipc::Transceiver::new(channel_tx, channel_rx)
            },
        })
    }
}
/// Brings up this controller core's memory protection and interrupt
/// controller, then constructs its (disconnected) IPC endpoints.
/// Call `.connect().await` on the result to run the descriptor
/// handshake.
///
/// Compiled only for Cortex-M targets; the host trybuild harness
/// (which never links `cortex-m`) skips it.
#[cfg(target_arch = "arm")]
fn init() -> IpcMemoryEndpoints {
    // SAFETY: `init` runs once during controller bring-up, in
    // privileged mode, before any other code touches the MPU.
    let mut __core = unsafe { ::cortex_m::Peripherals::steal() };
    // SAFETY: `init` holds exclusive privileged MPU access during
    // bring-up; `base`/`size` are this core's validated shared
    // region from the Consortium hardware layout.
    unsafe {
        ::consortium_runtime_mcu::mpu::disable_cache(
            &mut __core.MPU,
            0u8,
            541065216u32,
            16384u32,
        );
    }
    #[derive(Clone, Copy, Debug, Eq, PartialEq)]
    #[repr(u16)]
    pub enum BellaInterrupt {
        HSEM = 199u16,
    }
    unsafe impl ::cortex_m::interrupt::InterruptNumber for BellaInterrupt {
        fn number(self) -> u16 {
            self as u16
        }
    }
    // SAFETY: interrupt numbers are emitted from the validated
    // Consortium hardware database for this visible core.
    unsafe {
        ::cortex_m::peripheral::NVIC::unmask(BellaInterrupt::HSEM);
    }
    IpcMemoryEndpoints::new()
}

fn main() {}
