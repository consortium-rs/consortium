::consortium_ipc_transport_memory::channels!(LP);
::consortium_ipc_transport_memory::impl_channel!(
    LP, ::consortium_ipc::Secondary,
    ::consortium_ipc_transport_memory::bell::ipcc::IpccDoorbell <
    ::consortium_ipc::Secondary, 2usize >,
    ::consortium_shared_memory::regions::UncachedRegion, crate ::shared::PowerMode, crate
    ::shared::PowerStatus, ::consortium_codec::RkyvCodec < 128usize >, 1u8, 0u8,
    128usize,
);
#[cfg(target_arch = "arm")]
fn __consortium_install_channels(
    __db_ipcc2: ::consortium_hal_stm32mp2::Peri<
        'static,
        ::consortium_hal_stm32mp2::peripherals::IPCC2,
    >,
) {
    ::consortium_ipc_transport_memory::install::<
        channels::LP,
    >({
        // SAFETY: automatically generated by Consortium after matching with database
        let region = unsafe {
            ::consortium_shared_memory::regions::UncachedRegion::new(
                (537673728usize) as *mut u8,
                16384usize,
            )
        };
        let doorbell = ::consortium_ipc_transport_memory::bell::ipcc::IpccDoorbell::<
            ::consortium_ipc::Secondary,
            2usize,
        >::new(__db_ipcc2);
        // SAFETY: doorbell channel is verified to be valid in the config.
        let chan_tx = unsafe { ::consortium_ipc::Chan::new_unchecked(1u8) };
        // SAFETY: doorbell channel is verified to be valid in the config.
        let chan_rx = unsafe { ::consortium_ipc::Chan::new_unchecked(0u8) };
        // SAFETY: the base is offset 0x00 of the validated shared-memory
        // region, and the channels/doorbell/region are this side's.
        unsafe {
            ::consortium_ipc_transport_memory::SharedMemoryTransport::<
                ::consortium_ipc::Secondary,
                _,
                _,
            >::new(chan_tx, chan_rx, doorbell, region, (537673728usize) as *mut u8)
        }
    });
}
/// Runtime bring-up policy. Enabled manifest steps default on.
#[cfg(target_arch = "arm")]
#[non_exhaustive]
pub struct Config {
    pub logger: bool,
    pub mpu: bool,
    pub nvic: bool,
    pub time_driver: bool,
}
#[cfg(target_arch = "arm")]
impl ::core::default::Default for Config {
    fn default() -> Self {
        Self {
            logger: true,
            mpu: true,
            nvic: true,
            time_driver: true,
        }
    }
}
/// Brings up synchronous platform resources and installs each
/// unconnected IPC transport into its generated endpoint state.
#[cfg(target_arch = "arm")]
fn init(config: Config) -> (Peripherals, Channels) {
    if config.logger {}
    ::consortium_runtime_mcu::log::trace!(
        "consortium controller init: mpu/nvic bring-up"
    );
    if config.mpu {}
    if config.nvic {
        ::consortium_hal_stm32mp2::hal::nvic::unpend(
            ::consortium_hal_stm32mp2::hal::nvic::Irq(13u16),
        );
        // SAFETY: the interrupt comes from the validated Consortium
        // hardware database for this visible core, and the application
        // owns the matching vector.
        unsafe {
            ::consortium_hal_stm32mp2::hal::nvic::set_priority(
                ::consortium_hal_stm32mp2::hal::nvic::Irq(13u16),
                0x80u8,
            );
            ::consortium_hal_stm32mp2::hal::nvic::enable(
                ::consortium_hal_stm32mp2::hal::nvic::Irq(13u16),
            );
        }
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: NVIC enabled {} at priority 0x80 (id={})", "13",
            13u32
        );
    }
    ::consortium_runtime_mcu::log::trace!("before chip init");
    let __p = ::consortium_hal_stm32mp2::init();
    ::consortium_runtime_mcu::log::trace!("after chip init");
    if config.time_driver {}
    __consortium_install_channels(__p.IPCC2);
    let channels = Channels::take();
    let peripherals = Peripherals {};
    ::consortium_runtime_mcu::log::trace!("consortium controller init: resources ready");
    (peripherals, channels)
}
/// Error union suitable for `#[consortium_runtime_mcu::main]`.
#[cfg(target_arch = "arm")]
#[cfg_attr(target_os = "none", derive(Debug, defmt::Format))]
#[cfg_attr(not(target_os = "none"), derive(Debug))]
#[allow(dead_code)]
enum ConsortiumError {
    Connect(::consortium_ipc_transport_memory::ConnectError),
}
#[cfg(target_arch = "arm")]
impl ::core::convert::From<::consortium_ipc_transport_memory::ConnectError>
for ConsortiumError {
    fn from(e: ::consortium_ipc_transport_memory::ConnectError) -> Self {
        Self::Connect(e)
    }
}
