/// Runtime bring-up policy. Enabled manifest steps default on.
#[cfg(target_arch = "arm")]
#[non_exhaustive]
pub struct Config {
    pub logger: bool,
    pub mpu: bool,
    pub nvic: bool,
    pub time_driver: bool,
}
#[cfg(target_arch = "arm")]
impl ::core::default::Default for Config {
    fn default() -> Self {
        Self {
            logger: true,
            mpu: true,
            nvic: true,
            time_driver: true,
        }
    }
}
/// Brings up synchronous platform resources and installs each
/// unconnected IPC transport into its generated endpoint state.
#[cfg(target_arch = "arm")]
fn init(config: Config) -> (Peripherals, Channels) {
    if config.logger {}
    ::consortium_runtime_mcu::log::trace!(
        "consortium controller init: mpu/nvic bring-up"
    );
    if config.mpu {}
    if config.nvic {
        #[derive(Clone, Copy, Debug, Eq, PartialEq)]
        #[repr(u16)]
        pub enum BellaInterrupt {
            IPCC2 = 13u16,
        }
        unsafe impl ::cortex_m::interrupt::InterruptNumber for BellaInterrupt {
            fn number(self) -> u16 {
                self as u16
            }
        }
        // SAFETY: interrupt numbers are emitted from the validated
        // Consortium hardware database for this visible core.
        unsafe {
            ::consortium_hal_stm32mp2::hal::nvic::set_priority(
                BellaInterrupt::IPCC2 as u16,
                0x80,
            );
        }
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: NVIC set priority to 0x80 {} (id={})",
            stringify!(IPCC2), BellaInterrupt::IPCC2 as u32
        );
        ::cortex_m::peripheral::NVIC::unpend(BellaInterrupt::IPCC2);
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: NVIC unpend {} (id={})", stringify!(IPCC2),
            BellaInterrupt::IPCC2 as u32
        );
        // SAFETY: interrupt numbers are emitted from the validated
        // Consortium hardware database for this visible core.
        unsafe {
            ::cortex_m::peripheral::NVIC::unmask(BellaInterrupt::IPCC2);
        }
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: NVIC unmask {} (id={})", stringify!(IPCC2),
            BellaInterrupt::IPCC2 as u32
        );
    }
    let __p = ::consortium_hal_stm32mp2::init();
    if config.time_driver {
        ::consortium_hal_stm32mp2::timer_driver::bringup(__p.TIM2);
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: time driver up"
        );
    }
    __consortium_install_channels();
    let channels = Channels::take();
    let peripherals = Peripherals {};
    ::consortium_runtime_mcu::log::trace!("consortium controller init: resources ready");
    (peripherals, channels)
}
/// Error union suitable for `#[consortium_runtime_mcu::main]`.
#[cfg(target_arch = "arm")]
#[cfg_attr(target_os = "none", derive(Debug, defmt::Format))]
#[cfg_attr(not(target_os = "none"), derive(Debug))]
#[allow(dead_code)]
enum ConsortiumError {
    Connect(::consortium_ipc_transport_memory::ConnectError),
}
#[cfg(target_arch = "arm")]
impl ::core::convert::From<::consortium_ipc_transport_memory::ConnectError>
for ConsortiumError {
    fn from(e: ::consortium_ipc_transport_memory::ConnectError) -> Self {
        Self::Connect(e)
    }
}
