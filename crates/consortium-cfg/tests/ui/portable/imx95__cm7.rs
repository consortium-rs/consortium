/// Descriptor-handshake failure, with the doorbell-specific payload
/// erased so a single error type spans transceivers that use
/// different doorbells. `no_std`-safe (no `alloc`).
///
/// The `Descriptor` payload is surfaced through `Debug` in the
/// consuming binary, which dead-code analysis cannot see, so allow
/// the otherwise-"never read" field.
#[cfg_attr(target_os = "none", derive(Debug, defmt::Format))]
#[cfg_attr(not(target_os = "none"), derive(Debug))]
#[allow(dead_code)]
enum ConsortiumConnectError {
    /// The descriptor header/channel table was invalid or never reached
    /// the ready state.
    Descriptor(::consortium_ipc_transport_memory::DescriptorError),
    /// The doorbell signal failed during the handshake.
    Doorbell,
    /// Any other transport error during the handshake.
    Other,
}
/// IPC endpoints that have been *constructed* but not yet connected.
/// Call [`connect`](IpcMemoryEndpoints::connect) to run the descriptor
/// handshake and obtain usable transceivers.
struct IpcMemoryEndpoints {
    sensor: ::consortium_ipc_transport_memory::SharedMemoryTransport<
        ::consortium_ipc::Secondary,
        ::consortium_ipc_doorbell_mu::MuDoorbell<::consortium_ipc::Secondary, 7usize>,
        ::consortium_shared_memory::regions::SramRegion,
    >,
}
static mut SENSOR_RX_BUF: [u8; 128usize] = [0u8; 128usize];
static mut SENSOR_TX_BUF: [u8; 128usize] = [0u8; 128usize];
/// Connected IPC endpoints: each field is a ready-to-use transceiver.
struct IpcMemoryEndpointsConnected {
    sensor: ::consortium_ipc::Transceiver<
        crate::shared::MotionControl,
        crate::shared::SensorData,
        ::consortium_ipc_transport_memory::SharedMemoryTransportTx<
            ::consortium_ipc_transport_memory::Secondary,
            ::consortium_ipc_doorbell_mu::MuDoorbell<
                ::consortium_ipc::Secondary,
                7usize,
            >,
            ::consortium_shared_memory::regions::SramRegion,
        >,
        ::consortium_ipc_transport_memory::SharedMemoryTransportRx<
            ::consortium_ipc_transport_memory::Secondary,
            ::consortium_ipc_doorbell_mu::MuDoorbell<
                ::consortium_ipc::Secondary,
                7usize,
            >,
            ::consortium_shared_memory::regions::SramRegion,
        >,
        ::consortium_codec::RkyvCodec<128usize>,
    >,
}
impl IpcMemoryEndpoints {
    fn new() -> Self {
        Self {
            sensor: {
                // SAFETY: automatically generated by Consortium after matching with database
                let region = unsafe {
                    ::consortium_shared_memory::regions::SramRegion::new(
                        (541622272usize) as *mut u8,
                        16384usize,
                    )
                };
                // SAFETY: the base is the UIO-mapped doorbell register window,
                // resolved from the validated Consortium hardware database.
                let doorbell = unsafe {
                    ::consortium_ipc_doorbell_mu::MuDoorbell::<
                        ::consortium_ipc::Secondary,
                        7usize,
                    >::new(1111687168usize)
                };
                // SAFETY: doorbell channel is verified to be valid in the config.
                let chan_tx = unsafe { ::consortium_ipc::Chan::new_unchecked(7u8) };
                // SAFETY: doorbell channel is verified to be valid in the config.
                let chan_rx = unsafe { ::consortium_ipc::Chan::new_unchecked(6u8) };
                // SAFETY: the base is offset 0x00 of the validated shared-memory
                // region, and the channels/doorbell/region are this side's.
                unsafe {
                    ::consortium_ipc_transport_memory::SharedMemoryTransport::<
                        ::consortium_ipc::Secondary,
                        _,
                        _,
                    >::new(
                        chan_tx,
                        chan_rx,
                        doorbell,
                        region,
                        (541622272usize) as *mut u8,
                    )
                }
            },
        }
    }
    /// Runs the descriptor handshake for every transceiver and returns
    /// the connected endpoints. Each transceiver's primary side writes
    /// and the secondary side acks the descriptor before any traffic.
    async fn connect(
        self,
    ) -> ::core::result::Result<IpcMemoryEndpointsConnected, ConsortiumConnectError> {
        ::core::result::Result::Ok(IpcMemoryEndpointsConnected {
            sensor: {
                let transport = self.sensor;
                let (chan_tx, chan_rx) = transport.channels();
                // SAFETY: base covers the descriptor; this side is Secondary, so it
                // validates and acks the primary-written descriptor.
                unsafe {
                    <::consortium_ipc_transport_memory::SharedMemoryTransport<
                        ::consortium_ipc::Secondary,
                        ::consortium_ipc_doorbell_mu::MuDoorbell<
                            ::consortium_ipc::Secondary,
                            7usize,
                        >,
                        ::consortium_shared_memory::regions::SramRegion,
                    >>::descriptor_ack(
                            transport.base(),
                            2usize,
                            128usize,
                            transport.doorbell(),
                            chan_rx,
                            chan_tx,
                        )
                        .await
                }
                    .map_err(|__e| match __e {
                        ::consortium_ipc_transport_memory::Error::Descriptor(__d) => {
                            ConsortiumConnectError::Descriptor(__d)
                        }
                        ::consortium_ipc_transport_memory::Error::Doorbell(_) => {
                            ConsortiumConnectError::Doorbell
                        }
                        _ => ConsortiumConnectError::Other,
                    })?;
                let (t_tx, t_rx) = transport.split();
                let channel_tx = ::consortium_ipc::Channel::<
                    ::consortium_ipc::Tx,
                    crate::shared::MotionControl,
                    _,
                    ::consortium_codec::RkyvCodec<128usize>,
                >::new(
                    chan_tx,
                    t_tx,
                    {
                        // SAFETY: module-level static scratch buffer, borrowed once
                        // during initialization and never aliased afterwards.
                        unsafe { &mut *::core::ptr::addr_of_mut!(SENSOR_RX_BUF) }
                    },
                );
                let channel_rx = ::consortium_ipc::Channel::<
                    ::consortium_ipc::Rx,
                    crate::shared::SensorData,
                    _,
                    ::consortium_codec::RkyvCodec<128usize>,
                >::new(
                    chan_rx,
                    t_rx,
                    {
                        // SAFETY: module-level static scratch buffer, borrowed once
                        // during initialization and never aliased afterwards.
                        unsafe { &mut *::core::ptr::addr_of_mut!(SENSOR_TX_BUF) }
                    },
                );
                ::consortium_ipc::Transceiver::new(channel_tx, channel_rx)
            },
        })
    }
}
// SAFETY: installs the CMSIS-named LPIT1 vector the i.MX9 runtime
// dispatches; the handler only forwards to the time driver.
#[cfg(target_arch = "arm")]
#[unsafe(no_mangle)]
extern "C" fn LPIT1_IRQHandler() {
    ::consortium_hal_imx9::timer_driver::on_timer_interrupt();
}
/// Aggregate bring-up failure for this controller core's [`init`].
/// The payload is surfaced through `Debug`/`defmt` in the consuming
/// firmware binary, which dead-code analysis cannot see, so allow the
/// otherwise-"never read" field.
///
/// Gated to `target_arch = "arm"` alongside `init`/`Context`: the
/// host trybuild harness compiles only the endpoint module, never the
/// firmware entry surface.
#[cfg(target_arch = "arm")]
#[cfg_attr(target_os = "none", derive(Debug, defmt::Format))]
#[cfg_attr(not(target_os = "none"), derive(Debug))]
#[allow(dead_code)]
enum ConsortiumInitError {
    /// An IPC transceiver's descriptor handshake failed.
    Ipc(ConsortiumConnectError),
}
#[cfg(target_arch = "arm")]
impl ::core::convert::From<ConsortiumConnectError> for ConsortiumInitError {
    fn from(e: ConsortiumConnectError) -> Self {
        ConsortiumInitError::Ipc(e)
    }
}
/// Everything this manifest brings up for the controller core, handed
/// to the body by `#[consortium_runtime_mcu::main]`. `ipc_shm` holds
/// the connected transceivers. Gated with `init` (references the
/// `target_arch = "arm"`-only `Peripherals`).
#[cfg(target_arch = "arm")]
struct Context {
    ipc_shm: IpcMemoryEndpointsConnected,
    peripherals: Peripherals,
}
/// Brings up this controller core's logger, memory protection,
/// interrupt controller, and time driver, runs the IPC descriptor
/// handshake, and returns the connected [`Context`].
///
/// Compiled only for Cortex-M targets; the host trybuild harness
/// (which never links `cortex-m`) skips it.
#[cfg(target_arch = "arm")]
async fn init() -> ::core::result::Result<Context, ConsortiumInitError> {
    ::consortium_runtime_mcu::log::trace!(
        "consortium controller init: mpu/nvic bring-up"
    );
    // SAFETY: `init` runs once during controller bring-up, in
    // privileged mode, before any other code touches the MPU.
    let mut __core = unsafe { ::cortex_m::Peripherals::steal() };
    // SAFETY: `init` holds exclusive privileged MPU access during
    // bring-up; `base`/`size` are this core's validated shared
    // region from the Consortium hardware layout.
    unsafe {
        ::consortium_runtime_mcu::mpu::disable_cache(
            &mut __core.MPU,
            0u8,
            541622272u32,
            16384u32,
        );
        ::consortium_runtime_mcu::log::trace!(
            "consortium controller init: MPU carveout {} base={:#010x} size={:#010x}",
            0u8, 541622272u32, 16384u32
        );
    }
    #[derive(Clone, Copy, Debug, Eq, PartialEq)]
    #[repr(u16)]
    pub enum BellaInterrupt {
        MU7 = 207u16,
    }
    unsafe impl ::cortex_m::interrupt::InterruptNumber for BellaInterrupt {
        fn number(self) -> u16 {
            self as u16
        }
    }
    // SAFETY: interrupt numbers are emitted from the validated
    // Consortium hardware database for this visible core.
    unsafe {
        ::consortium_hal_imx9::hal::nvic::set_priority(BellaInterrupt::MU7 as u16, 0x80);
    }
    ::consortium_runtime_mcu::log::trace!(
        "consortium controller init: NVIC set priority to 0x80 {} (id={})",
        stringify!(MU7), BellaInterrupt::MU7 as u32
    );
    ::cortex_m::peripheral::NVIC::unpend(BellaInterrupt::MU7);
    ::consortium_runtime_mcu::log::trace!(
        "consortium controller init: NVIC unpend {} (id={})", stringify!(MU7),
        BellaInterrupt::MU7 as u32
    );
    // SAFETY: interrupt numbers are emitted from the validated
    // Consortium hardware database for this visible core.
    unsafe {
        ::cortex_m::peripheral::NVIC::unmask(BellaInterrupt::MU7);
    }
    ::consortium_runtime_mcu::log::trace!(
        "consortium controller init: NVIC unmask {} (id={})", stringify!(MU7),
        BellaInterrupt::MU7 as u32
    );
    // SAFETY: `init` runs once during controller bring-up, in privileged
    // mode, before any `embassy-time` use; `bringup` takes exclusive
    // ownership of the time-driver timer and its NVIC line.
    unsafe {
        ::consortium_hal_imx9::timer_driver::bringup();
    }
    ::consortium_runtime_mcu::log::trace!("consortium controller init: time driver up");
    ::consortium_runtime_mcu::log::trace!(
        "consortium controller init: connecting ipc endpoints"
    );
    let ipc_shm = IpcMemoryEndpoints::new().connect().await?;
    let peripherals = peripherals();
    ::consortium_runtime_mcu::log::trace!("consortium controller init: context ready");
    ::core::result::Result::Ok(Context { ipc_shm, peripherals })
}
/// Peripherals this core owns, constructed by [`peripherals`].
#[cfg(target_arch = "arm")]
pub struct Peripherals {
    pub gpio2: ::consortium_hal_imx9::gpio::Gpio,
    pub lpi2c1: ::consortium_hal_imx9::i2c::I2c,
}
#[cfg(target_arch = "arm")]
static LPI2C1_STATE: ::consortium_hal_imx9::i2c::I2cState = ::consortium_hal_imx9::i2c::I2cState::new();
#[cfg(target_arch = "arm")]
#[unsafe(no_mangle)]
extern "C" fn LPI2C1_IRQHandler() {
    LPI2C1_STATE.on_interrupt();
}
/// Brings up this core's owned peripherals: enables their interrupts
/// and constructs the HAL drivers with their bases baked in.
///
/// Compiled only for Cortex-M targets; the host trybuild harness skips
/// it along with the rest of the peripheral module.
#[cfg(target_arch = "arm")]
fn peripherals() -> Peripherals {
    // SAFETY: the interrupt number comes from the validated
    // Consortium chip map; a handler for it is installed above,
    // and bring-up runs once before other code masks interrupts.
    unsafe {
        ::consortium_hal_imx9::hal::nvic::set_priority(13u16, 0x80u8);
        ::consortium_hal_imx9::hal::nvic::enable(13u16);
    }
    // SAFETY: `base` is this core's validated GPIO port base from
    // the Consortium chip map, owned exclusively by this driver.
    let gpio2 = unsafe {
        ::consortium_hal_imx9::gpio::Gpio::new(1132527616u32 as *mut ())
    };
    // SAFETY: `base` is this core's validated I2C base from the
    // Consortium chip map, owned exclusively by this driver;
    // its dedicated state's interrupt is routed above.
    let lpi2c1 = unsafe {
        ::consortium_hal_imx9::i2c::I2c::new(
            1144258560u32 as *mut (),
            24000000u32,
            100000u32,
            &LPI2C1_STATE,
        )
    };
    Peripherals { gpio2, lpi2c1 }
}

