#[cfg(target_arch = "arm")]
fn __consortium_install_channels(
    __db_mu8_mub: ::consortium_hal_imx9::Peri<
        'static,
        ::consortium_hal_imx9::peripherals::MU8_MUB,
    >,
    __db_mu7_mub: ::consortium_hal_imx9::Peri<
        'static,
        ::consortium_hal_imx9::peripherals::MU7_MUB,
    >,
) {
    ::consortium_ipc_transport_memory::install::<
        channels::LP,
    >({
        // SAFETY: automatically generated by Consortium after matching with database
        let region = unsafe {
            ::consortium_core::regions::UncachedRegion::new(
                (2284863488usize) as *mut u8,
                16384usize,
            )
        };
        let doorbell = ::consortium_core::bell::mu::MuDoorbell::<
            ::consortium_ipc::Secondary,
            8usize,
        >::new(__db_mu8_mub);
        // SAFETY: doorbell channel is verified to be valid in the config.
        let chan_tx = unsafe { ::consortium_ipc::Chan::new_unchecked(5u8) };
        // SAFETY: doorbell channel is verified to be valid in the config.
        let chan_rx = unsafe { ::consortium_ipc::Chan::new_unchecked(4u8) };
        // SAFETY: doorbell channel is verified to be valid in the config.
        let chan_ack_tx = unsafe { ::consortium_ipc::Chan::new_unchecked(1u8) };
        // SAFETY: doorbell channel is verified to be valid in the config.
        let chan_ack_rx = unsafe { ::consortium_ipc::Chan::new_unchecked(0u8) };
        // SAFETY: the region is this channel's validated shared-memory
        // window, whose offset 0x00 holds the descriptor, and the
        // channels/doorbell are this side's.
        unsafe {
            ::consortium_ipc_transport_memory::SharedMemoryTransport::<
                ::consortium_ipc::Secondary,
                _,
                _,
            >::new_acked(chan_tx, chan_rx, chan_ack_tx, chan_ack_rx, doorbell, region)
        }
    });
    ::consortium_ipc_transport_memory::install::<
        channels::SENSOR,
    >({
        // SAFETY: automatically generated by Consortium after matching with database
        let region = unsafe {
            ::consortium_core::regions::CachedRegion::new(
                (2284879872usize) as *mut u8,
                16384usize,
            )
        };
        let doorbell = ::consortium_core::bell::mu::MuDoorbell::<
            ::consortium_ipc::Secondary,
            7usize,
        >::new(__db_mu7_mub);
        // SAFETY: doorbell channel is verified to be valid in the config.
        let chan_tx = unsafe { ::consortium_ipc::Chan::new_unchecked(7u8) };
        // SAFETY: doorbell channel is verified to be valid in the config.
        let chan_rx = unsafe { ::consortium_ipc::Chan::new_unchecked(6u8) };
        // SAFETY: the region is this channel's validated shared-memory
        // window, whose offset 0x00 holds the descriptor, and the
        // channels/doorbell are this side's.
        unsafe {
            ::consortium_ipc_transport_memory::SharedMemoryTransport::<
                ::consortium_ipc::Secondary,
                _,
                _,
            >::new(chan_tx, chan_rx, doorbell, region)
        }
    });
}
