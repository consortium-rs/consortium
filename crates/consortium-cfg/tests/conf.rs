//! End-to-end `Consortium.toml` -> IR -> codegen snapshots.
//!
//! Every `tests/configs/<name>/Consortium.toml` is parsed, lowered to the
//! `components` IR, and rendered to a per-config Markdown artifact at
//! `tests/configs/<name>/artifacts.snap`. The artifact bundles the three
//! generated outputs a build driver consumes:
//!
//! - `## UIO Definition`: the Linux-side `generic-uio` DTS nodes.
//! - `## NVIC Initialization`: per controller-core Cortex-M NVIC enablement.
//! - `## Initialization code`: per-core IPC endpoint construction, one
//!   `### <core>` aspect each.
//!
//! Snapshots are regenerated by setting `UPDATE_SNAPSHOTS=1` (or any value);
//! otherwise a mismatch fails the test and writes `artifacts.snap.new`.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use consortium_cfg::Session;
use consortium_cfg::bridge::LoweredIr;
use consortium_cfg_common::config::VisibleCore;
use consortium_dts::ToDts;
use proc_macro2::TokenStream;

/// Pretty-print generated tokens by wrapping them in a function body, so both
/// item sequences (struct + impl) and statements (NVIC unmask blocks) format
/// cleanly and the snapshot fails if the output stops being valid Rust.
fn pretty(tokens: TokenStream) -> String {
    let wrapped: TokenStream = quote::quote! { fn _generated() { #tokens } };
    let file = syn::parse_file(&wrapped.to_string()).expect("generated code should parse as Rust");
    prettyplease::unparse(&file)
}

/// The `ty_crate` path used for generated message types in these fixtures.
fn ty_crate() -> syn::Path {
    syn::parse_str("::shared").unwrap()
}

/// Every distinct core that participates in any transceiver, ordered with the
/// AP first and controller cores sorted by name for stable snapshots.
fn cores(ir: &LoweredIr) -> Vec<VisibleCore> {
    let mut seen: BTreeMap<String, VisibleCore> = BTreeMap::new();
    let mut has_ap = false;
    for t in ir.shuhan.transceivers() {
        for (core, _) in [&t.channel_primary, &t.channel_secondary] {
            if *core == VisibleCore::Ap {
                has_ap = true;
            } else {
                seen.insert(core.to_string(), *core);
            }
        }
    }

    let mut out = Vec::new();
    if has_ap {
        out.push(VisibleCore::Ap);
    }
    out.extend(seen.into_values());
    out
}

/// Renders the full Markdown artifact for one lowered manifest.
fn render(ir: &LoweredIr) -> String {
    let ty_crate = ty_crate();
    let mut md = String::new();

    md.push_str("# Generated artifacts\n\n");

    // ## UIO Definition
    md.push_str("## UIO Definition\n\n");
    if ir.uio.is_empty() {
        md.push_str("_No UIO devices._\n\n");
    } else {
        for (name, device) in &ir.uio {
            writeln!(md, "### {name}\n").unwrap();
            md.push_str("```dts\n");
            md.push_str(device.to_node(name.as_str()).to_dts().trim_end());
            md.push_str("\n```\n\n");
        }
    }

    // ## NVIC Initialization
    md.push_str("## NVIC Initialization\n\n");
    let mut any_nvic = false;
    for core in cores(ir) {
        if core == VisibleCore::Ap {
            continue;
        }
        if let Some(tokens) = ir.bella.nvic_enable(&core) {
            any_nvic = true;
            writeln!(md, "### {core}\n").unwrap();
            md.push_str("```rust\n");
            md.push_str(pretty(tokens).trim_end());
            md.push_str("\n```\n\n");
        }
    }
    if !any_nvic {
        md.push_str("_No controller-core doorbell interrupts._\n\n");
    }

    // ## Initialization code
    md.push_str("## Initialization code\n\n");
    for core in cores(ir) {
        // The AP renders its UIO bring-up + `init` wrapper; controller cores
        // render just their per-core `IpcMemoryEndpoints`.
        writeln!(md, "### {core}\n").unwrap();
        md.push_str("```rust\n");
        md.push_str(pretty(ir.initialize(core, &ty_crate)).trim_end());
        md.push_str("\n```\n\n");
    }

    md.trim_end().to_string()
}

/// Compares `actual` against the committed `path`, regenerating it when
/// `UPDATE_SNAPSHOTS` is set (or when the file is absent on first run).
fn assert_artifact(path: &Path, actual: &str) {
    let actual = format!("{}\n", actual.trim_end());
    let update = std::env::var_os("UPDATE_SNAPSHOTS").is_some();

    match fs::read_to_string(path) {
        Ok(expected) if expected == actual => {}
        Ok(_) if update => fs::write(path, &actual).expect("write updated snapshot"),
        Ok(expected) => {
            let new_path = path.with_extension("snap.new");
            fs::write(&new_path, &actual).expect("write .new snapshot");
            panic!(
                "snapshot mismatch for {}\nwrote new output to {}\nrerun with UPDATE_SNAPSHOTS=1 to accept\n\n--- expected ---\n{expected}\n--- actual ---\n{actual}",
                path.display(),
                new_path.display(),
            );
        }
        Err(_) => fs::write(path, &actual).expect("write initial snapshot"),
    }
}

/// The `tests/configs` directory next to this test file.
fn configs_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("configs")
}

#[test]
fn config_artifacts_match_snapshots() {
    let dir = configs_dir();
    let mut entries: Vec<_> = fs::read_dir(&dir)
        .expect("configs dir exists")
        .map(|e| e.expect("dir entry").path())
        .filter(|p| p.is_dir())
        .collect();
    entries.sort();

    assert!(!entries.is_empty(), "no config fixtures under {dir:?}");

    for config in entries {
        let manifest = config.join("Consortium.toml");
        let toml = fs::read_to_string(&manifest)
            .unwrap_or_else(|e| panic!("read {}: {e}", manifest.display()));

        let session = Session::from_toml(&toml)
            .unwrap_or_else(|e| panic!("parse {}: {e}", manifest.display()));
        let ir = session
            .lower()
            .unwrap_or_else(|e| panic!("lower {}: {e}", manifest.display()));

        assert_artifact(&config.join("artifacts.snap"), &render(&ir));
    }
}
