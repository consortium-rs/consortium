//! Remoteproc resource-table layout.
//!
//! Re-exports the raw `.resource_table` structures generated by
//! [`consortium_runtime_sys`] from `rsc_table.h`, so firmware can lay out the
//! ELF section a Linux host parses when booting this coprocessor.
//!
//! The bindgen [`ResourceTable`]/[`FwRscVdev`] types model the kernel *parser*
//! view: their trailing arrays (`offset[]`, `vring[]`) are flexible array
//! members and hold no data, so they cannot be statically initialized. To
//! *emit* a table, declare a concrete struct whose header is followed by a
//! fixed `offset[N]` and the entries laid out inline — see
//! [`SharedResourceTable`] below. Each entry is a `fw_rsc_hdr` (a single `type`
//! word) immediately followed by its payload, and `offset[i]` points at that
//! word.

pub use consortium_runtime_sys::*;

use core::mem::offset_of;

/// Number of resource entries described by [`SharedResourceTable`].
const NUM_RESOURCE_ENTRIES: usize = 2;

/// virtio device id for rpmsg (`VIRTIO_ID_RPMSG`, see `virtio_ids.h`).
const VIRTIO_ID_RPMSG: u32 = 7;
/// rpmsg feature bitmap advertised to the host (`VIRTIO_RPMSG_F_NS`).
const RPMSG_FEATURES: u32 = 1;
/// Number of vrings in the vdev entry (one TX, one RX).
const VRING_COUNT: u8 = 2;
/// Buffers per vring; must be a power of two.
const VRING_NUM_BUFFS: u32 = 16;
/// Vring alignment negotiated with the host.
const VRING_ALIGN: u32 = 16;

/// A concrete resource table: an rpmsg vdev with two vrings plus a trace
/// buffer. This mirrors the STM32Cube `struct shared_resource_table`; adjust the
/// entry set and addresses for your platform.
///
/// `#[repr(C, packed)]` matches the on-wire, byte-packed ELF-section layout the
/// host parses. Do not take references to individual fields (they are
/// unaligned); read/write whole values instead.
#[repr(C, packed)]
pub struct SharedResourceTable {
    // --- struct resource_table header ---
    ver: u32,
    num: u32,
    reserved: [u32; 2],
    offset: [u32; NUM_RESOURCE_ENTRIES],

    // --- entry 0: rpmsg vdev (fw_rsc_hdr.type + fw_rsc_vdev payload) ---
    vdev_type: u32,
    vdev: FwRscVdev,
    // The two vrings belong to `vdev` (its flexible `vring[]`); laying them out
    // as adjacent fields reproduces that trailing array in memory.
    vring0: FwRscVdevVring,
    vring1: FwRscVdevVring,

    // --- entry 1: trace buffer (fw_rsc_hdr.type + fw_rsc_trace payload) ---
    trace_type: u32,
    trace: FwRscTrace,
}

/// Builds a fixed-size `name[32]` field from a byte string, zero-padded/truncated.
const fn rsc_name(s: &[u8]) -> [u8; 32] {
    let mut name = [0u8; 32];
    let mut i = 0;
    while i < s.len() && i < 31 {
        name[i] = s[i];
        i += 1;
    }
    name
}

impl SharedResourceTable {
    /// Constructs the table.
    ///
    /// * `trace_da` / `trace_len` — device address and size of the trace ring the
    ///   coprocessor writes logs into (exposed by the host as `trace0`).
    ///
    /// The vring device addresses are left as [`FW_RSC_ADDR_ANY`], asking the
    /// host to allocate them; set concrete `da`/`pa` values if your carveout is
    /// fixed.
    pub const fn new(trace_da: u32, trace_len: u32) -> Self {
        Self {
            ver: 1,
            num: NUM_RESOURCE_ENTRIES as u32,
            reserved: [0, 0],
            offset: [
                offset_of!(SharedResourceTable, vdev_type) as u32,
                offset_of!(SharedResourceTable, trace_type) as u32,
            ],

            vdev_type: FwResourceType_RSC_VDEV,
            vdev: FwRscVdev {
                id: VIRTIO_ID_RPMSG,
                notifyid: 0,
                dfeatures: RPMSG_FEATURES,
                gfeatures: 0,
                config_len: 0,
                status: 0,
                num_of_vrings: VRING_COUNT,
                reserved: [0, 0],
                vring: __IncompleteArrayField::new(),
            },
            vring0: FwRscVdevVring {
                da: FW_RSC_ADDR_ANY as u32,
                align: VRING_ALIGN,
                num: VRING_NUM_BUFFS,
                notifyid: 0,
                pa: 0,
            },
            vring1: FwRscVdevVring {
                da: FW_RSC_ADDR_ANY as u32,
                align: VRING_ALIGN,
                num: VRING_NUM_BUFFS,
                notifyid: 1,
                pa: 0,
            },

            trace_type: FwResourceType_RSC_TRACE,
            trace: FwRscTrace {
                da: trace_da,
                len: trace_len,
                reserved: 0,
                name: rsc_name(b"cm_log"),
            },
        }
    }
}

// SAFETY: the resource table is a plain POD layout read cross-core by the host;
// it holds no `Sync`-unsafe interior state. `#[repr(C, packed)]` fixes the ABI.
unsafe impl Sync for SharedResourceTable {}

/// The resource table linked into the `.resource_table` ELF section the host
/// reads when booting this firmware. Replace the trace address/size with the
/// buffer your firmware actually logs into.
#[unsafe(link_section = ".resource_table")]
#[used]
pub static RSC_TABLE: SharedResourceTable = SharedResourceTable::new(0x0000_0000, 0);
